function result=RepairParentDerivativeTrial_v3(outputDirectory)
%REPAIRPARENTDERIVATIVETRIAL_V3 Retry the measured topology-filter obstruction.
% A correction to the parent is a solver repair, not a daughter attachment.
    v3=V3Root_v3(mfilename('fullpath'));
    V3LegacyAddPath_v3(genpath(V3Path_v3(v3)));if nargin<1,outputDirectory=fileparts(mfilename('fullpath'));end
    outputDirectory=V3OutputPath_v3(outputDirectory);
    gates=load(V3Path_v3(fullfile(outputDirectory,'solver_validation_summary.mat')),'summary');
    assert(gates.summary.all_required_gates_passed,'Finish focused solver gates first.');
    old=load(V3Path_v3(fullfile(v3,'Research_v3','runs','full','parent_attempt_1.mat')));
    p=old.info.parameter(1:10);q=old.info.mode;
    seed=struct('state',old.guess,'mode',q,'parameter',p,'return_policy','BL-marked-apex-return', ...
        'occurrence',1,'provenance',struct('kind','historical-parent-trial-causal-repair', ...
        'artifact','Research_v3/runs/full/parent_attempt_1.mat','original_primary_message',old.info.output.message, ...
        'old_finalization_message',old.info.message));
    jacobian=EventOrderChartJacobian_v3(struct('PhysicalParameter',p, ...
        'RelativeCandidateSteps',[3e-4,1e-4],'MaximumRelativeError',.01,'UseRichardson',false));
    options=struct('Symmetry','none','Energy',1.1,'MaxWallSeconds',240, ...
        'SolverOptions',struct('Algorithm','newton','MaxIterations',25, ...
        'MaxFunctionEvaluations',500,'Jacobian',jacobian,'UseBroyden',true,'JacobianRefreshInterval',5));
    registration=struct('model_id','v3-autonomous-first-directed-root-compressive-stance', ...
        'target','repair original failed full-space E1.1 parent trial', ...
        'hypothesis','strict event-cluster compatibility prevented a common physical C1 derivative', ...
        'allowed_regular_chart','BL1 flight-to-flight TD-all then LO-all transverse zero-compression cohorts', ...
        'source_sha256',RoundSHA256_v3(fullfile(v3,'Numerics_v3','PeriodicSolutionSolver_v3.m')), ...
        'jacobian_sha256',RoundSHA256_v3(fullfile(v3,'Numerics_v3','EventOrderChartJacobian_v3.m')), ...
        'registered_before_execution_utc',char(datetime('now','TimeZone','UTC')), ...
        'acceptance_unchanged',true,'branch_attachment_claimed',false);
    save(V3Path_v3(fullfile(outputDirectory,'parent_derivative_repair_registration.mat')),'seed','options','registration','-v7');
    [solution,report]=PeriodicSolutionSolver_v3(seed,options);
    parent=zeros(14,1);parent(3)=1.1;
    result=struct('schema_version','parent-derivative-causal-repair-v3-1', ...
        'accepted',report.accepted,'status',report.status,'initial_residual',report.initial_scaled_norm, ...
        'final_residual',report.final_scaled_norm,'full_closure',report.full_closure, ...
        'distance_to_parent',norm(report.final_candidate-parent,inf), ...
        'primary_failure',report.primary_failure,'replay_failure',report.replay_failure, ...
        'accepted_Newton_iterations',member(report.solver,'acceptedNewtonIterations',0), ...
        'map_evaluations',member(report.solver,'mapEvaluationCount',0), ...
        'jacobian_reliable',member(report.solver,'jacobianReliable',false), ...
        'per_column_reliability',member(report.solver,'perColumnReliability',[]), ...
        'elapsed_seconds',report.elapsed_seconds,'branch_attachment_claimed',false);
    if isfield(report.classification,'label'),result.gait=report.classification.label;end
    save(V3Path_v3(fullfile(outputDirectory,'parent_derivative_repair.mat')),'seed','options','registration','solution','report','result','-v7');
    f=fopen(V3Path_v3(fullfile(outputDirectory,'parent_derivative_repair.json')),'w');cleanup=onCleanup(@()fclose(f));
    fprintf(f,'%s\n',jsonencode(result,'PrettyPrint',true));disp(result);
end
function value=member(data,name,fallback)
    value=fallback;if isfield(data,name),value=data.(name);end
end
