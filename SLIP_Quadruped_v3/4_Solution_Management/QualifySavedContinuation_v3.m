function qualification=QualifySavedContinuation_v3(branch,cfg,physicalFlights,allowedLabels)
%QUALIFYSAVEDCONTINUATION_V3 Stored-service publication gates, zero maps.
% Requires every retained point's original independent physical admission.
% It neither repairs a point nor replaces missing historical acceptance.
    required={'full_closure','mode_closure','target_energy','trajectory_energy_variation', ...
        'unscaled_family_equations','family_constraint','physical_inequalities','primitive_identity','replay_determinism'};
    rows=struct([]);
    for k=1:numel(branch.points)
        point=branch.points(k);orbit=point.orbit;report=field(point.solverInfo,'periodic_solution_report',struct());
        gates=field(report,'acceptance_gates',struct());gateCount=0;
        for j=1:numel(required),v=field(gates,required{j},false);gateCount=gateCount+double(isscalar(v)&&isfinite(v)&&logical(v));end
        primitive=field(report,'primitive',struct());gait=field(report,'classification',struct());
        baseline=isequal(orbit.parameter(:),cfg.baseline_v3_parameters(:));
        closure=norm(orbit.poincare_state(2:end)-orbit.initial_state(2:end),inf);
        E=QuadrupedEnergy_v3.evaluate(orbit.initial_state,orbit.initial_mode,orbit.parameter);speed=orbit.stride_displacement(1)/orbit.period;
        pitch=max(abs(orbit.trajectory.state(:,5)));events=sum(~[orbit.event_history.is_stop]);
        domain=isfinite(E)&&E>=cfg.domain.energy(1)&&E<=cfg.domain.energy(2)&&isfinite(speed) ...
            &&speed>=cfg.domain.mean_speed(1)&&speed<=cfg.domain.mean_speed(2) ...
            &&isfinite(orbit.period)&&orbit.period>0&&orbit.period<=cfg.domain.primitive_period_max ...
            &&~isempty(pitch)&&isfinite(pitch)&&pitch<=cfg.domain.pitch_abs_max&&events>0&&events<=cfg.domain.event_count_max;
        primitivePassed=strcmp(char(field(primitive,'status','')),'primitive_within_checked_bound')&&field(primitive,'cover_count',Inf)==1;
        actualLabel=char(field(gait,'label','unresolved'));actualFlights=field(gait,'flight_count',NaN);
        checks=struct('saved_service_accepted',field(report,'accepted',false),'all_nine_original_gates',gateCount==9, ...
            'exact_baseline_parameters',baseline,'registered_domain',domain,'primitive_cover_one',primitivePassed, ...
            'complete_saved_full_closure',isfinite(closure)&&closure<=cfg.acceptance.full_closure, ...
            'actual_class_and_flight_placement',actualFlights==physicalFlights&&any(strcmp(actualLabel,allowedLabels)), ...
            'finite_arclength',isscalar(point.arclength)&&isfinite(point.arclength));
        names=fieldnames(checks);values=structfun(@logical,checks);qualified=all(values);
        row=struct('source_record_index',k,'qualified',qualified,'checks',checks,'failed_checks',{names(~values)}, ...
            'nine_gate_pass_count',gateCount,'energy',E,'period',orbit.period,'signed_drift',orbit.stride_displacement(1), ...
            'full_closure',closure,'classification_label',actualLabel,'physical_flights',actualFlights,'arclength',point.arclength);
        if isempty(rows),rows=row;else,rows(end+1)=row;end %#ok<AGROW>
    end
    pass=~isempty(rows)&&all([rows.qualified]);
    source=[mfilename('fullpath'),'.m'];
    qualification=struct('schema_version','saved-continuation-physical-publication-v3-1','qualified',pass, ...
        'point_count',numel(rows),'points',rows,'new_maps',0,'new_simulations',0,'new_replay_admissions',0, ...
        'missing_historical_gates_replaced',false,'ancestry_or_attachment_claimed',false, ...
        'qualifier_source',source,'qualifier_source_sha256',RoundSHA256_v3(source));
end
function value=field(data,name,fallback),value=fallback;if isstruct(data)&&isscalar(data)&&isfield(data,name),value=data.(name);end,end
