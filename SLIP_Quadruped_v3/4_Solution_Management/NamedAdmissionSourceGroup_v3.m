function group=NamedAdmissionSourceGroup_v3(solutions,samples,study,key,abbreviation)
%NAMEDADMISSIONSOURCEGROUP_V3 Retain unordered native source admissions.
    root=V3Root_v3(mfilename('fullpath'));solutions=reshape(solutions,1,[]);assert(numel(solutions)==numel(samples)&&~isempty(samples));
    records=struct([]);
    for j=1:numel(solutions)
        orbit=solutions{j};sample=samples(j);path=relative(sample.source_path);
        record=struct('solution_index',j,'source_path',path,'source_sha256',sample.source_sha256, ...
            'source_record_index',1,'component_index',1,'record_kind','independent_admission_samples', ...
            'original_admission_source_path',path,'original_admission_source_sha256',sample.source_sha256, ...
            'original_admission_source_record_index',1,'classification_label',sample.classification_label, ...
            'classification_status',sample.classification_status,'physical_flight_count',sample.physical_flights, ...
            'energy',sample.energy,'period',orbit.period,'signed_drift',orbit.stride_displacement(1), ...
            'mean_speed',orbit.stride_displacement(1)/orbit.period,'saved_full_closure',sample.full_closure, ...
            'return_policy_name',char(orbit.return_policy_name),'BL_touchdowns_per_return',orbit.section_chart.BL_touchdowns_per_return, ...
            'fresh_replay_performed_by_publication',false);
        if isempty(records),records=record;else,records(end+1)=record;end %#ok<AGROW>
    end
    component=struct('index',1,'source_path',records(1).source_path,'source_sha256',records(1).source_sha256, ...
        'record_indices',1:numel(solutions),'record_kind','independent_admission_samples','ordered_source_records',1:numel(solutions), ...
        'arclength',[],'continuation_direction','','joins_to_other_components_claimed',false, ...
        'source_record_start_index',1,'source_record_end_index',numel(solutions), ...
        'continuation_metadata',struct('samples_are_ordered_continuation',false,'original_samples',samples));
    group=struct('study',study,'key',key,'kind','additional_native_admission_group','abbreviation',abbreviation, ...
        'display_name',[abbreviation,' independently admitted source samples'],'dataset_type','accepted_orbit_samples', ...
        'note','Native admissions retain their source task and measured classification. These unordered samples create no continuation, distinct-family, connectivity or ancestry claim.', ...
        'solutions',{solutions},'records',records,'components',component,'branch_designation','');
    function path=relative(path)
        path=V3Path_v3(path);path=char(java.io.File(path).getCanonicalPath());
        assert(startsWith(path,[root,filesep]));path=strrep(path(numel(root)+2:end),filesep,'/');
    end
end
