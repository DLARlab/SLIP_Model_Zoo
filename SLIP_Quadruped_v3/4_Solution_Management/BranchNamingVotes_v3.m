function audit=BranchNamingVotes_v3(levels)
%BRANCHNAMINGVOTES_V3 One equally weighted vote at each of 20 speed levels.
% Each level has complete, labels (all resolved intersections), qualified.
% An incomplete level cannot demonstrate agreement among known limbs.
    if ~isstruct(levels)||numel(levels)~=20|| ...
            ~all(isfield(levels,{'complete','labels','qualified'}))
        error('BranchNamingVotes_v3:Levels','Exactly twenty registered level records are required.');
    end
    votes=repmat({''},1,20);resolved=false(1,20);qualified=false(1,20);
    intersections=zeros(1,20);
    for j=1:20
        labels=cellstr(string(levels(j).labels));intersections(j)=numel(labels);
        resolved(j)=isequal(levels(j).complete,true)&&~isempty(labels)&&all(~cellfun(@isempty,labels));
        if ~resolved(j),votes{j}='INCOMPLETE';continue;end
        labels=unique(labels);
        if numel(labels)>1,votes{j}='MULTIVALUED';else,votes{j}=labels{1};end
        qualified(j)=all(levels(j).qualified(:))&&numel(levels(j).qualified)==intersections(j);
    end
    categories=unique(votes,'stable');counts=cellfun(@(category)sum(strcmp(votes,category)),categories);
    top=max(counts);winners=categories(counts==top);uniqueMode=numel(winners)==1;
    mode='';if uniqueMode,mode=winners{1};end
    diagnostic=@(label)isempty(label)||ismember(string(label),["INCOMPLETE","MULTIVALUED"]) ...
        ||~isempty(regexp(label,'^[BHFG][MU][0-9]+$','once'));
    winnerQualified=uniqueMode&&~diagnostic(mode)&&all(qualified(strcmp(votes,mode)));
    complete=all(resolved);
    audit=struct('schema_version','branch-naming-votes-v3.1','level_count',20, ...
        'votes',{votes},'categories',{categories},'counts',counts,'unique_mode',uniqueMode, ...
        'mode',mode,'tied_modes',{winners},'mode_count',top,'mode_fraction',top/20, ...
        'has_majority',uniqueMode&&top>10,'complete',complete, ...
        'resolved_level_count',sum(resolved),'qualified_level_count',sum(qualified), ...
        'intersection_count_by_level',intersections, ...
        'diagnostic_vote_count',sum(cellfun(diagnostic,votes)), ...
        'multivalued_vote_count',sum(strcmp(votes,'MULTIVALUED')), ...
        'canonical_name_qualified',complete&&winnerQualified, ...
        'provisional',~(complete&&winnerQualified), ...
        'rule','Unique most frequent category among twenty equal speed locations; no strict majority requirement.');
end
