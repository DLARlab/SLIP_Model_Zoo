function qualification=QualifySavedAdmission_v3(data,cfg)
%QUALIFYSAVEDADMISSION_V3 Saved physical publication contract, zero maps.
% This checks an original report and stored complete orbit against the actual
% tranche registration. It creates no new acceptance, replay or classification.
    report=field(data,'report',struct());orbit=field(data,'solution',field(data,'orbit',[]));
    required={'full_closure','mode_closure','target_energy','trajectory_energy_variation', ...
        'unscaled_family_equations','family_constraint','physical_inequalities','primitive_identity','replay_determinism'};
    gates=field(report,'acceptance_gates',struct());gateCount=0;
    for k=1:numel(required)
        value=field(gates,required{k},false);gateCount=gateCount+double(isscalar(value)&&isfinite(value)&&logical(value));
    end
    primitive=field(report,'primitive',struct());gait=field(report,'classification',struct());
    label=char(field(gait,'label',''));abbreviation=char(field(gait,'abbreviation',''));status=char(field(gait,'status',''));
    flights=field(gait,'flight_count',NaN);energy=NaN;period=NaN;drift=NaN;speed=NaN;pitch=NaN;events=NaN;closure=NaN;
    baseline=false;domain=false;
    if ~isempty(orbit)
        energy=QuadrupedEnergy_v3.evaluate(orbit.initial_state,orbit.initial_mode,orbit.parameter);
        period=orbit.period;drift=orbit.stride_displacement(1);speed=drift/period;
        pitch=max(abs(orbit.trajectory.state(:,5)));events=sum(~[orbit.event_history.is_stop]);
        closure=norm(orbit.poincare_state(2:end)-orbit.initial_state(2:end),inf);
        baseline=isequal(orbit.parameter(:),cfg.baseline_v3_parameters(:));
        domain=isfinite(energy)&&energy>=cfg.domain.energy(1)&&energy<=cfg.domain.energy(2) ...
            &&isfinite(speed)&&speed>=cfg.domain.mean_speed(1)&&speed<=cfg.domain.mean_speed(2) ...
            &&isfinite(period)&&period>0&&period<=cfg.domain.primitive_period_max ...
            &&~isempty(pitch)&&isfinite(pitch)&&pitch<=cfg.domain.pitch_abs_max ...
            &&events>0&&events<=cfg.domain.event_count_max;
    end
    reportedClosure=field(report,'full_closure',NaN);
    checks=struct('saved_orbit_present',~isempty(orbit),'original_service_accepted',field(report,'accepted',false), ...
        'all_nine_original_gates',gateCount==9,'exact_baseline_parameters',baseline,'registered_domain',domain, ...
        'primitive_cover_one',strcmp(char(field(primitive,'status','')),'primitive_within_checked_bound') ...
            &&field(primitive,'cover_count',Inf)==1, ...
        'reported_full_closure',isscalar(reportedClosure)&&isfinite(reportedClosure)&&reportedClosure<=cfg.acceptance.full_closure, ...
        'complete_saved_full_closure',isfinite(closure)&&closure<=cfg.acceptance.full_closure, ...
        'saved_class_and_flight_placement',~isempty(label)&&~isempty(abbreviation)&&~isempty(status) ...
            &&isscalar(flights)&&ismember(flights,[1,2]));
    names=fieldnames(checks);values=structfun(@logical,checks);source=[mfilename('fullpath'),'.m'];
    qualification=struct('schema_version','saved-admission-physical-publication-v3-1','qualified',all(values), ...
        'checks',checks,'failed_checks',{names(~values)},'nine_gate_pass_count',gateCount, ...
        'energy',energy,'period',period,'signed_drift',drift,'mean_speed',speed, ...
        'pitch_abs_max',pitch,'physical_event_count',events,'saved_full_closure',closure,'reported_full_closure',reportedClosure, ...
        'classification_label',label,'classification_abbreviation',abbreviation,'classification_status',status,'physical_flights',flights, ...
        'registered_domain',cfg.domain,'new_maps',0,'new_simulations',0,'new_admissions',0, ...
        'qualifier_source',source,'qualifier_source_sha256',RoundSHA256_v3(source));
end
function value=field(data,name,fallback),value=fallback;if isstruct(data)&&isscalar(data)&&isfield(data,name),value=data.(name);end,end
