        function continuationCarriesFRLOThroughApexChart(testCase)
            % Requirement I: the same full cycle survives a section chart swap.
            [problem, map] = testCase.orderingProblem();
            solver = RootSolver_v3(struct( ...
                'Algorithm', 'newton', ...
                'FunctionTolerance', 1e-9, ...
                'ResidualAcceptanceTolerance', 1e-7));
            continuation = NumericalContinuation1D_v3(struct( ...
                'RootSolver', solver, ...
                'ActiveParameter', 'mu', ...
                'StopOnFailure', true));
            parameterValues = [0.10, 0.05, 0, -0.05, -0.10];
            branch = continuation.run( ...
                problem, [1; 0], 0.10, 1, parameterValues);

            testCase.verifyEqual(branch.count, numel(parameterValues));
            testCase.verifyTrue(branch.success);
            modes = cellfun(@double, branch.mode);
            testCase.verifyEqual(modes, [1, 1, 0, 0, 0]);
            testCase.verifyEqual(branch.period, ones(1, 5), ...
                'AbsTol', 2e-6);
            testCase.verifyEqual(branch.return_multiplicity, ones(1, 5));
            testCase.verifyEqual(branch.return_policy, repmat( ...
                {'EventCycleReturnPolicy_v3'}, 1, 5));
            testCase.verifyEqual(branch.return_policy_name, repmat( ...
                {'event-cycle-return'}, 1, 5));
            testCase.verifyEqual(branch.cycle_return_policy, ...
                branch.return_policy);
            testCase.verifyEqual(branch.candidate_section_count, ...
                ones(1, 5));
            testCase.verifyEqual(branch.candidate_apex_count, ones(1, 5));
            testCase.verifyEqual(branch.accepted_crossing_index, ...
                ones(1, 5));
            testCase.verifyEqual(branch.accepted_apex_index, ones(1, 5));
            testCase.verifyLessThan( ...
                max(abs([branch.points.residualNorm])), 1e-7);

            afterApex = string({branch.event_history{1}.type});
            beforeApex = string({branch.event_history{end}.type});
            testCase.verifyEqual(afterApex, ["FR_LO", "FR_TD"]);
            testCase.verifyEqual(beforeApex, ["FR_TD", "FR_LO"]);
            testCase.verifyTrue(isa(map.ReturnPolicy, ...
                'EventCycleReturnPolicy_v3'));
            testCase.verifyEqual(branch.topology_boundary, ...
                logical([0, 0, 1, 0, 0]));

            transitionSolve = branch.solver_info{3};
            testCase.verifyEqual(numel(transitionSolve.candidateModes), 2);
            testCase.verifyEqual(double(transitionSolve.selectedMode), 0);
            testCase.verifyLessThan( ...
                numel(transitionSolve.candidateModes), 16);
            testCase.verifyNotEmpty(transitionSolve.modeResolution);
            testCase.verifyTrue(any(string( ...
                {transitionSolve.modeResolution.source}) == ...
                "local-section-mode-resolver"));
            coincident = branch.points(3).orbit.section_coincident_events;
            testCase.verifyNotEmpty(coincident);
            testCase.verifyTrue(any(string({coincident.type}) == "FR_LO"));
            boundaryDetector = HybridBoundaryDetector_v3();
            boundaries = boundaryDetector.detect(branch);
            boundaryTypes = string({boundaries.type});
            testCase.verifyTrue(any(boundaryTypes == ...
                "section_event_coincidence"));
            testCase.verifyTrue(any(boundaryTypes == "section_mode_change"));

            boundaryFloquet = FloquetAnalysis_v3(struct( ...
                'TangentIndices', 1, ...
                'RelativeStep', 1e-4)).analyze(map, [1; 0], 0, 0);
            testCase.verifyFalse(boundaryFloquet.reliable);
            testCase.verifyTrue(boundaryFloquet.sectionEventCoincidence);
            testCase.verifyNotEmpty(boundaryFloquet.sectionCoincidentEvents);
        end

        function fullCycleFloquetMultiplierIsProductOfLocalReturns(testCase)
            % Requirement N: differentiate the accepted two-apex hybrid map.
            gamma = 0.3;
            system = createSyntheticReturnPolicySystem_v3( ...
                'two-apex-radial');
            simulator = HybridSimulator_v3(struct( ...
                'RelTol', 1e-11, 'AbsTol', 1e-13));
            section = PoincareSection_v3.apex(2);
            options = struct('MaxReturnTime', 2.5, ...
                'MaxSectionCrossings', 4, 'MaxCycleEvents', 8, ...
                'ArmTolerance', 1e-7);
            firstMap = PoincareMap_v3(system, section, simulator, ...
                FirstReturnPolicy_v3(), options);
            cycleMap = PoincareMap_v3(system, section, simulator, ...
                EventCycleReturnPolicy_v3(), options);

            localAnalyzer = FloquetAnalysis_v3(struct( ...
                'TangentIndices', 1, 'RelativeStep', 1e-4, ...
                'RequireDiscreteClosure', false));
            local0 = localAnalyzer.analyze(firstMap, [1; 0], 0, gamma);
            local1 = localAnalyzer.analyze(firstMap, [1; 0], 1, gamma);
            full = FloquetAnalysis_v3(struct( ...
                'TangentIndices', 1, ...
                'RelativeStep', 1e-4)).analyze( ...
                    cycleMap, [1; 0], 0, gamma);

            expectedLocal = exp(-2 * gamma);
            expectedCycle = exp(-4 * gamma);
            testCase.verifyEqual(local0.multipliers, expectedLocal, ...
                'AbsTol', 3e-8);
            testCase.verifyEqual(local1.multipliers, expectedLocal, ...
                'AbsTol', 3e-8);
            testCase.verifyEqual(full.multipliers, expectedCycle, ...
                'AbsTol', 3e-8);
            testCase.verifyEqual(full.multipliers, ...
                local0.multipliers * local1.multipliers, 'AbsTol', 3e-8);
            testCase.verifyEqual(full.return_multiplicity, 2);
            testCase.verifyEqual(full.baseMapInfo.period, 2, ...
                'AbsTol', 3e-7);
            testCase.verifyTrue(full.reliable);
            testCase.verifyTrue(full.finiteDifference.allReliable);
            testCase.verifyGreaterThan( ...
                full.finiteDifference.selectedSteps(1), sqrt(eps));
            testCase.verifyEmpty(full.ambientPoincareMatrix);
        end

        function detectsNamedCandidatesAndRejectsUnreliableInterval(testCase)
            % Requirement O: bracketed smooth candidates need reliable data.
            angle = 0.4;
            multipliers = [ ...
                 0.8,  1.2; ...
                -0.8, -1.2; ...
                 0.9 * exp(1i * angle), 1.1 * exp(1i * angle); ...
                 0.9 * exp(-1i * angle), 1.1 * exp(-1i * angle)];
            detector = BifurcationDetector_v3();
            [events, tracks] = detector.detect(multipliers, [0, 1]);

            types = string({events.type});
            testCase.verifyTrue(any(types == "unit_multiplier_candidate"));
            testCase.verifyTrue(any(types == ...
                "period_doubling_candidate"));
            testCase.verifyTrue(any(types == "Neimark_Sacker_candidate"));
            testCase.verifyEqual(size(tracks.multipliers), [4, 2]);
            testCase.verifyEqual([events.location], ...
                0.5 * ones(1, numel(events)), 'AbsTol', 1e-12);

            branch = struct();
            branch.stability = { ...
                struct('multipliers', 0.8, 'eigenvectors', 1, ...
                    'reliable', true), ...
                struct('multipliers', 1.2, 'eigenvectors', 1, ...
                    'reliable', false)};
            branch.continuationCoordinate = [0, 1];
            branch.cyclic_signature = {'A', 'A'};
            branch.return_multiplicity = [1, 1];
            branch.topology_boundary = [false, false];
            [rejected, rejectedTracks] = detector.detect(branch);
            testCase.verifyEmpty(rejected);
            testCase.verifyEqual(rejectedTracks.reliable, [true, false]);

            topologyBranch = branch;
            topologyBranch.stability{2}.reliable = true;
            topologyBranch.topology_boundary = [false, true];
            topologyRejected = detector.detect(topologyBranch);
            testCase.verifyEmpty(topologyRejected);

            nanBranch = struct();
            nanBranch.stability = { ...
                struct('multipliers', 0.8, 'eigenvectors', 1, ...
                    'reliable', true), ...
                struct('multipliers', NaN, 'eigenvectors', NaN, ...
                    'reliable', false), ...
                struct('multipliers', 1.2, 'eigenvectors', 1, ...
                    'reliable', true)};
            nanBranch.continuationCoordinate = [0, 0.5, 1];
            nanBranch.cyclic_signature = {'A', 'A', 'A'};
            nanBranch.return_multiplicity = [1, 1, 1];
            nanBranch.topology_boundary = [false, false, false];
            [nanEvents, nanTracks] = detector.detect(nanBranch);
            testCase.verifyEmpty(nanEvents);
            testCase.verifyEqual(nanTracks.reliable, [true, false, true]);
        end

