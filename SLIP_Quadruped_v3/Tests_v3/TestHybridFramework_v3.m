        function actualParameterAsymmetricQuadrupedOrbitClosesCycle(testCase)
            % Requirement L coverage for a genuinely event-discovered,
            % non-pronking v3 orbit. The old asymmetric fixtures remain a
            % separate migration incompatibility because they suppress
            % additional guard crossings before their prescribed endpoint.
            schema = testCase.QuadrupedFramework.schema;
            finiteDifference = FiniteDifferenceJacobian_v3(struct( ...
                'Method', 'forward', 'RelativeStep', 1e-7, ...
                'FailurePolicy', 'nan'));
            solver = RootSolver_v3(struct( ...
                'Jacobian', finiteDifference, ...
                'Algorithm', 'newton', ...
                'FunctionTolerance', 1e-8, ...
                'ResidualAcceptanceTolerance', 1e-7, ...
                'MaxIterations', 20, ...
                'MaxFunctionEvaluations', 1200));
            continuation = NumericalContinuation1D_v3(struct( ...
                'RootSolver', solver, ...
                'ActiveParameter', 'k_l_f', ...
                'StopOnFailure', true));

            baseOrbit = testCase.QuadrupedOrbit;
            targetFrontStiffness = ...
                baseOrbit.parameter(schema.Parameter.k_l_f) + 0.02;
            branch = continuation.run( ...
                testCase.QuadrupedFramework.residual, ...
                baseOrbit.initial_state(schema.Root.UnknownIndices), ...
                baseOrbit.parameter, baseOrbit.initial_mode, ...
                targetFrontStiffness);

            testCase.verifyTrue(branch.success);
            testCase.verifyEqual(branch.count, 1);
            point = branch.points(1);
            testCase.verifyLessThan(point.residualNorm, 1e-7);
            testCase.verifyEqual(point.return_multiplicity, 1);
            testCase.verifyGreaterThan(point.period, 0);
            testCase.verifyEqual(point.p(schema.Parameter.k_l_f), ...
                targetFrontStiffness, 'AbsTol', eps(targetFrontStiffness));
            testCase.verifyNotEqual( ...
                point.p(schema.Parameter.k_l_b), ...
                point.p(schema.Parameter.k_l_f));

            events = point.event_history;
            eventNames = string({events.type});
            testCase.verifyEqual(numel(events), 8);
            for expectedName = string(schema.Event.Names)
                testCase.verifyEqual(sum(eventNames == expectedName), 1);
            end
            eventCounts = point.event_counts;
            testCase.verifyEqual([eventCounts.touchdown_count], ones(1, 4));
            testCase.verifyEqual([eventCounts.liftoff_count], ones(1, 4));

            backTouchdown = events(find(eventNames == "BL_TD", 1)).time;
            frontTouchdown = events(find(eventNames == "FL_TD", 1)).time;
            backLiftoff = events(find(eventNames == "BL_LO", 1)).time;
            frontLiftoff = events(find(eventNames == "FL_LO", 1)).time;
            testCase.verifyGreaterThan( ...
                abs(frontTouchdown - backTouchdown), 1e-5);
            testCase.verifyGreaterThan( ...
                abs(frontLiftoff - backLiftoff), 1e-5);

            mapInfo = point.solverInfo.evaluationInfo.map_info;
            testCase.verifyEqual(mapInfo.initial_mode, mapInfo.final_mode);
            testCase.verifyTrue(mapInfo.cycle_complete);
            testCase.verifyLessThan( ...
                numel(point.solverInfo.candidateModes), 16);
            testCase.verifyFalse(isprop(point.orbit, 'gait_type'));
        end

        function availableAsymmetricFixtureIsExplicitlyAudited(testCase)
            % Requirement L fixture audit. A representative point is also
            % replayed so the documented migration incompatibility is an
            % executed result, not an inference from stored event times.
            fixture = fullfile(testCase.RepositoryRoot, 'SLIP_Quadruped', ...
                'P1_Breaking_Symmetries_Leads_to_Diverse_Qudrupedal_Gaits', ...
                '1_Roadmap', 'BD1_20_2_BG.mat');
            testCase.verifyTrue(isfile(fixture));
            data = load(fixture, 'results');
            testCase.verifySize(data.results, [29, 474]);
            storedEventTimes = data.results(14:21, end);
            testCase.verifyGreaterThan( ...
                max(storedEventTimes) - min(storedEventTimes), 1e-3);

            legacyPoint = data.results(:, 204);
            unknown = LegacyStateAdapter_v3.toV3Unknown( ...
                legacyPoint(1:13));
            schema = testCase.QuadrupedFramework.schema;
            state = zeros(schema.State.Dimension, 1);
            state(schema.Root.UnknownIndices) = unknown;
            parameter = LegacyParameterAdapter_v3.toV3( ...
                legacyPoint(23:29), 'v2-exact');
            eventTimes = legacyPoint(14:21);
            oldMode = logical([ ...
                eventTimes(1) > eventTimes(2); ...
                eventTimes(3) > eventTimes(4); ...
                eventTimes(5) > eventTimes(6); ...
                eventTimes(7) > eventTimes(8)]);
            mode = LegacyModeAdapter_v3.toV3(oldMode);
            guardValues = ...
                testCase.QuadrupedFramework.system.GuardFunctionsComponent ...
                .legValues(state, parameter);
            testCase.verifyGreaterThan(min(guardValues), 0.1);
            testCase.verifyError(@() ...
                testCase.QuadrupedFramework.map.evaluate( ...
                    state, mode, parameter), ...
                'ContinuousDynamics_v3:TensileStance');
        end

        function pseudoArclengthCorrectsStateAndParameter(testCase)
            crossings = repmat(struct('index', 0), 2, 1);
            crossings(1).index = 1;
            crossings(2).index = 2;
            metadata = struct( ...
                'integration_success', true, ...
                'discrete_closed', true, ...
                'cycle_complete', true, ...
                'return_policy_accepted', true, ...
                'return_policy', 'EventCycleReturnPolicy_v3', ...
                'return_policy_name', 'event-cycle-return', ...
                'candidate_section_crossings', {crossings}, ...
                'candidate_apex_count', 2, ...
                'accepted_crossing_index', 2, ...
                'accepted_apex_index', 2, ...
                'return_multiplicity', 2, ...
                'section_relative_event_signature', 'A>B', ...
                'cyclic_event_signature', 'A>B', ...
                'guard_transversality_margin', 1, ...
                'section_transversality', 1, ...
                'topology_margins', struct('guard_transversality', 1));
            residual = @(u, p, q, context) deal( ...
                u - p(1) + 0 * numel(fieldnames(context)), metadata);
            solver = RootSolver_v3(struct('Algorithm', 'newton'));
            continuation = PseudoArclengthContinuation_v3(struct( ...
                'RootSolver', solver, ...
                'ActiveParameterIndex', 1, ...
                'StepSize', 0.1, ...
                'MaxPoints', 4, ...
                'InitialDirection', 1));
            branch = continuation.run(residual, 0, 0, []);
            testCase.verifyEqual(branch.count, 4);
            testCase.verifyLessThan(max(abs(branch.x - branch.p)), 1e-8);
            testCase.verifyEqual(branch.return_policy, repmat( ...
                {'EventCycleReturnPolicy_v3'}, 1, 4));
            testCase.verifyEqual(branch.return_policy_name, repmat( ...
                {'event-cycle-return'}, 1, 4));
            testCase.verifyEqual(branch.cycle_return_policy, ...
                branch.return_policy);
            testCase.verifyEqual(branch.candidate_section_count, ...
                2 * ones(1, 4));
            testCase.verifyEqual(branch.candidate_apex_count, ...
                2 * ones(1, 4));
            testCase.verifyEqual(branch.accepted_crossing_index, ...
                2 * ones(1, 4));
            testCase.verifyEqual(branch.accepted_apex_index, ...
                2 * ones(1, 4));
            testCase.verifyEqual([branch.points.return_multiplicity], ...
                2 * ones(1, 4));
        end

        function classicalFiniteDifferenceUsesAdaptiveCoordinateScale(testCase)
            finiteDifference = FiniteDifferenceJacobian_v3();
            x = [0; 3];
            [jacobian, ~, info] = finiteDifference.compute( ...
                @(z) [z(1)^2; sin(z(2))], x);
            expectedSteps = sqrt(eps) * (1 + abs(x));
            testCase.verifyEqual(info.steps, expectedSteps, ...
                'AbsTol', 10 * eps);
            testCase.verifyEqual(jacobian(2, 2), cos(3), ...
                'AbsTol', 2e-7);
        end

