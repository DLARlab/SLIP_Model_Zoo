        function [value, info] = exchangeBranchResidual(u, p, q) %#ok<INUSD>
            fixedCoordinate = (u(1) + u(2)) ./ sqrt(2);
            breakingCoordinate = (u(1) - u(2)) ./ sqrt(2);
            basis = [1, 1; 1, -1] ./ sqrt(2);
            value = basis * [fixedCoordinate; ...
                breakingCoordinate .* (breakingCoordinate - p(1))];
            info = TestBranchSwitching_v3.acceptedInfo('TD>LO>Apex');
        end

