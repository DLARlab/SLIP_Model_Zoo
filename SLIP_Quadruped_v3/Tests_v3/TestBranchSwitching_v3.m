                'cyclic_event_signature', 'TD>LO', ...
                'section_relative_event_signature', sectionSignature, ...
                'event_cluster_signature', '{TD}>{LO}', ...
                'guard_transversality_margin', 1, ...
                'section_transversality', 1);
