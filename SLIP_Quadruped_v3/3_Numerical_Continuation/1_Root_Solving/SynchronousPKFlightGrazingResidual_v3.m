classdef SynchronousPKFlightGrazingResidual_v3 < handle
    %SYNCHRONOUSPKFLIGHTGRAZINGRESIDUAL_V3 Interior-flight acquisition only.
    % w=[z8;tCritical], using the unchanged forced-phase residual's F7.
    % flight-grazing:       [F7; g(tCritical); DgF(tCritical)].
    % stationary-owned-PAL: [F7; originalPAL; DgF(tCritical)].
    % These are square root equations, not an autonomous return/admission.
    % No createOrbit method is supplied. The native BL/PSS problem, its
    % independent replays, all gates and inward-offset checks remain required.

    properties (SetAccess=private)
        Inner
        Schema
        PhysicalParameter
        Kind
        ResidualScale
        DeadlineUnixSeconds
        DeadlineMonotonicNs
    end

    methods
        function obj=SynchronousPKFlightGrazingResidual_v3(inner,options)
            assert(strcmp(class(inner),'SynchronousPKPhaseResidual_v3')&&isscalar(inner), ...
                'SynchronousPKFlightGrazing:Inner','Use one existing native forced-phase acquisition residual.');
            assert(isstruct(options)&&isscalar(options)&&isfield(options,'Kind') ...
                &&all(ismember(fieldnames(options),{'Kind','ResidualScale'})), ...
                'SynchronousPKFlightGrazing:Options','Declare the boundary or stationary-owned-PAL root equations.');
            assert(ischar(options.Kind)&&isrow(options.Kind) ...
                &&ismember(options.Kind,{'flight-grazing','stationary-owned-PAL'}), ...
                'SynchronousPKFlightGrazing:Kind','Use flight-grazing or stationary-owned-PAL.');
            assert(strcmp(inner.ConstraintKind,'owned-PAL'), ...
                'SynchronousPKFlightGrazing:PAL','Retain the original owned PAL plane in the inner problem.');
            obj.Inner=inner;obj.Schema=inner.Schema;obj.PhysicalParameter=inner.PhysicalParameter;
            obj.Kind=options.Kind;obj.ResidualScale=[inner.ResidualScale(1:7);1;1];
            if isfield(options,'ResidualScale'),obj.ResidualScale=options.ResidualScale(:);end
            validateattributes(obj.ResidualScale,{'numeric'},{'real','finite','positive','vector','numel',9});
            obj.DeadlineUnixSeconds=inner.DeadlineUnixSeconds;
            obj.DeadlineMonotonicNs=inner.DeadlineMonotonicNs;
            obj.checkDeadline();
        end

        function x=fullState(obj,w,varargin)
            validateattributes(w,{'numeric'},{'real','finite','vector','numel',9});
            w=w(:);x=obj.Inner.fullState(w(1:8),varargin{:});
        end

        function r=evaluate(obj,w,p,q)
            [r,~]=obj.evaluateWithInfo(w,p,q);
        end

        function [r,info]=evaluateWithInfo(obj,w,p,q,varargin) %#ok<INUSD>
            obj.checkDeadline();
            validateattributes(w,{'numeric'},{'real','finite','vector','numel',9});
            w=w(:);z=w(1:8);time=w(9);
            p=obj.Schema.validateParameter(p);q=obj.Schema.validateMode(q);
            assert(isequal(p,obj.PhysicalParameter)&&~any(q), ...
                'SynchronousPKFlightGrazing:FixedProblem','Keep literal physical parameters and the all-flight mode.');
            assert(time>0&&time<z(6), ...
                'SynchronousPKFlightGrazing:Interior','Critical time must be strictly inside the FIRST flight.');
            [~,innerInfo]=obj.Inner.evaluateWithInfo(z,p,q);
            assert(isstruct(innerInfo)&&isscalar(innerInfo) ...
                &&numel(innerInfo.physical_residual)==8, ...
                'SynchronousPKFlightGrazing:InnerRows','The unchanged inner problem must return its eight literal physical rows.');
            geometry=obj.firstFlightGeometry(z,time,p);
            originalPAL=obj.Inner.Constraint.normal.'*(z(1:5)-obj.Inner.Constraint.reference) ...
                -obj.Inner.Constraint.target;
            if strcmp(obj.Kind,'flight-grazing'),selector=geometry.guard_values(1);
            else,selector=originalPAL;end
            raw=[innerInfo.physical_residual(1:7);selector;geometry.guard_rates(1)];
            r=raw./obj.ResidualScale;
            assert(all(isfinite(r)),'SynchronousPKFlightGrazing:Finite','Acquisition residual rows must remain finite.');
            info=struct('acquisition_evaluation_completed',true, ...
                'acquisition_chart','exact-centered-upright-synchronous-PK-interior-first-flight', ...
                'equation_kind',obj.Kind,'root_dimension',9,'forced_phase_trial',true, ...
                'autonomous_return_claimed',false,'native_admission_claimed',false, ...
                'global_minimum_claimed',false,'continuous_coverage_claimed',false, ...
                'initial_state',innerInfo.initial_state,'source_state',innerInfo.source_state, ...
                'source_is_exact_chart',innerInfo.source_is_exact_chart, ...
                'new_candidate_chart_allowed',innerInfo.new_candidate_chart_allowed, ...
                'phase_durations',z(6:8),'critical_time',time, ...
                'critical_time_domain_margins',[time;z(6)-time], ...
                'critical_flight_geometry',geometry,'inner_evaluation',innerInfo, ...
                'original_PAL_residual',originalPAL,'selector_residual',selector, ...
                'stationarity_residual',geometry.guard_rates(1), ...
                'all_critical_guard_values',geometry.guard_values, ...
                'all_critical_guard_rates',geometry.guard_rates, ...
                'all_critical_guard_second_derivatives',geometry.guard_second_derivatives, ...
                'first_flight_initial_guard_values',innerInfo.initial_guard_values, ...
                'first_flight_terminal_guard_values',innerInfo.all_td_guard_values, ...
                'physical_residual',raw,'scaled_residual',r,'residual_scale',obj.ResidualScale, ...
                'scope','One first-flight stationary/grazing root in the exact forced chart. No resetting critical time, phase projection, autonomous event acceptance, physical endpoint or global minimum certificate.', ...
                'handoff_required','Inspect first AND final flight stationary points/endpoints with explicit completeness limits; test a positive inward offset in original BL/PSS with full closure/all9/fresh replays and actual owned capture.');
            obj.checkDeadline();
        end

        function [modes,details]=modeCandidates(obj,varargin)
            [modes,details]=obj.Inner.modeCandidates(varargin{:});
        end
    end

    methods (Access=private)
        function geometry=firstFlightGeometry(obj,z,time,p)
            expanded=obj.Schema.expandParameters(p);legs=obj.Schema.Leg.Count;
            angle=zeros(legs,1);rate=angle;acceleration=angle;frequency=angle;
            values=angle;rates=angle;curvature=angle;
            fixedGradient=zeros(legs,8);stationarityGradient=zeros(legs,8);
            fixedHessian=zeros(8,8,legs);jointHessian=zeros(9,9,legs);
            heightGradient=zeros(8,1);heightGradient(2)=1;
            for k=1:legs
                L=expanded.l_0(k);ks=expanded.k_s(k);rest=expanded.rsla(k);
                if ks==0
                    nu=0;C=1;D=time;Ct=0;
                    angle(k)=z(3)+z(4)*time;rate(k)=z(4);acceleration(k)=0;
                else
                    nu=sqrt(ks/L^2);
                    assert(isfinite(nu)&&nu>0,'SynchronousPKFlightGrazing:Frequency', ...
                        'Positive swing stiffness must resolve to a finite positive flight frequency.');
                    C=cos(nu*time);D=sin(nu*time)/nu;Ct=-nu*sin(nu*time);
                    angle(k)=rest+(z(3)-rest)*C+z(4)*D;
                    rate(k)=(z(3)-rest)*Ct+z(4)*C;
                    acceleration(k)=-(ks/L^2)*(angle(k)-rest);
                end
                frequency(k)=nu;
                A=zeros(8,1);A(3)=C;A(4)=D;
                B=zeros(8,1);B(3)=Ct;B(4)=C;
                values(k)=z(2)-time^2/2-L*cos(angle(k));
                rates(k)=-time+L*sin(angle(k))*rate(k);
                curvature(k)=-1+L*(cos(angle(k))*rate(k)^2+sin(angle(k))*acceleration(k));
                gz=heightGradient+L*sin(angle(k))*A;
                gtz=L*cos(angle(k))*rate(k)*A+L*sin(angle(k))*B;
                H=L*cos(angle(k))*(A*A.');
                fixedGradient(k,:)=gz.';stationarityGradient(k,:)=gtz.';
                fixedHessian(:,:,k)=H;
                jointHessian(:,:,k)=[H,gtz;gtz.',curvature(k)];
            end
            s=obj.Schema;st=s.State;state=obj.Inner.fullState(z);
            state(st.x)=state(st.x)+z(1)*time;state(st.y)=z(2)-time^2/2;state(st.dy)=-time;
            state(s.Leg.AngleIndices)=angle;state(s.Leg.RateIndices)=rate;
            flow=zeros(st.Dimension,1);flow(st.x)=z(1);flow(st.y)=-time;flow(st.dy)=-1;
            flow(s.Leg.AngleIndices)=rate;flow(s.Leg.RateIndices)=acceleration;
            nativeValues=obj.Inner.Guards.legValues(state,p);
            nativeRates=obj.Inner.Guards.legLieDerivatives(state,flow,p);
            geometry=struct('flight','first','time_from_initial_apex',time,'state',state, ...
                'analytic_flow',flow,'leg_names',{s.Leg.Names}, ...
                'leg_rest_lengths',expanded.l_0,'swing_stiffness',expanded.k_s, ...
                'rest_swing_angles',expanded.rsla,'angular_frequency',frequency, ...
                'leg_angles',angle,'leg_rates',rate,'leg_accelerations',acceleration, ...
                'touchdown_event_ids',s.Event.IDs(s.Event.IsTouchdown).', ...
                'guard_event_directions',s.Event.Directions(s.Event.IsTouchdown).', ...
                'guard_values',values,'guard_rates',rates,'guard_second_derivatives',curvature, ...
                'native_guard_values',nativeValues,'native_guard_rates',nativeRates, ...
                'analytic_minus_native_guard_values',values-nativeValues, ...
                'analytic_minus_native_guard_rates',rates-nativeRates, ...
                'fixed_time_z_gradient',fixedGradient,'fixed_time_z_hessian',fixedHessian, ...
                'fixed_time_stationarity_z_gradient',stationarityGradient, ...
                'joint_z_time_gradient',[fixedGradient,rates], ...
                'joint_z_time_hessian',jointHessian, ...
                'joint_stationarity_gradient',[stationarityGradient,curvature], ...
                'coordinate_order','z=[dx;height;alphaBL;omegaBL;energy;tFlightDown;tStance;tFlightUp], then tCritical', ...
                'derivative_scope','Analytic fixed-parameter first-flight guard derivatives only. F7 derivatives and final-flight completeness are not certified by these arrays.', ...
                'native_consistency_scope','Guard geometry and Dg times the constructed analytic flow only; not an independent ODE integration or autonomous native-return check.');
        end

        function checkDeadline(obj)
            assert(double(java.lang.System.nanoTime())<obj.DeadlineMonotonicNs ...
                &&posixtime(datetime('now','TimeZone','UTC'))<obj.DeadlineUnixSeconds, ...
                'SynchronousPKFlightGrazing:Deadline','The original phase-acquisition deadline expired.');
        end
    end
end
