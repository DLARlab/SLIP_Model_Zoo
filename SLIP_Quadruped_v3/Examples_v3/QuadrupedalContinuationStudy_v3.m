function result = assessPhysicalBranchSwitchCandidates(floquet, mu, options)
    result = struct('attempted', true, ...
        'parameter_value', mu, 'reliable_source', false, ...
        'nearest_plus_one_distance', Inf, ...
        'nearest_minus_one_distance', Inf, ...
        'nearest_unit_circle_distance', Inf, ...
        'validated_bracket', false, 'switch_attempted', false, ...
        'outcome', 'no reliable Floquet grid available');
    if ~isstruct(floquet) || ~isfield(floquet, 'grid_results') || ...
            isempty(floquet.grid_results)
        return
    end
    reliable = find([floquet.grid_results.reliable], 1, 'last');
    if isempty(reliable)
        result.outcome = ['No reliable symmetry-restricted matrix was ', ...
            'available; no branch switch was attempted.'];
        return
    end
    multipliers = floquet.grid_results(reliable).multipliers(:);
    result.reliable_source = true;
    result.nearest_plus_one_distance = min(abs(multipliers - 1));
    result.nearest_minus_one_distance = min(abs(multipliers + 1));
    result.nearest_unit_circle_distance = min(abs(abs(multipliers) - 1));
    candidate = min([result.nearest_plus_one_distance, ...
        result.nearest_minus_one_distance, ...
        result.nearest_unit_circle_distance]);
    if candidate <= options.PhysicalBifurcationScreeningTolerance
        result.outcome = ['A single-point spectral proximity was found, ', ...
            'but no parameter bracket/refined critical point was available; ', ...
            'branch switching is mathematically inadmissible.'];
    else
        result.outcome = ['The actual orbit was screened for +1, -1, and ', ...
            'unit-circle candidates; none met the screening tolerance.'];
    end
end

