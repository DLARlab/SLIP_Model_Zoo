function distance = matchedMultiplierDistance(left, right)
    left = left(:);
    right = right(:);
    if numel(left) ~= numel(right) || isempty(left) || ...
            any(~isfinite(left)) || any(~isfinite(right))
        distance = Inf;
        return
    end
    remaining = right;
    distances = zeros(numel(left), 1);
    [~, order] = sort(abs(left), 'descend');
    for index = 1:numel(order)
        value = left(order(index));
        [distances(index), match] = min(abs(remaining - value));
        remaining(match) = [];
    end
    distance = max(distances);
end

