function [z, p, q] = selectAsymmetricReference(simple, z0, p0, q0, index)
    z = z0;
    p = p0;
    q = q0;
    if ~isfield(simple, 'points') || isempty(simple.points)
        p(index) = p(index) + 0.02;
        return
    end
    values = arrayfun(@(entry) entry.parameter(index), simple.points);
    % Use the most asymmetric accepted point.  A small front/back split can
    % lie within the event-cluster tolerance at the larger external
    % Floquet steps even though the left/right cluster is structural.
    candidate = find(abs(values - p0(index)) > 1e-12 & ...
        [simple.points.converged], 1, 'last');
    if isempty(candidate)
        candidate = find([simple.points.converged], 1, 'last');
    end
    if ~isempty(candidate)
        z = simple.points(candidate).reduced_unknown(:);
        p = simple.points(candidate).parameter(:);
        q = simple.points(candidate).mode;
    end
end

function [residual, details] = evaluateLeftRightResidual( ...
        reduced, p, q, problem, context)
    if nargin < 5 || isempty(context)
        context = struct();
    end
    unknown = unpackLeftRightUnknown(reduced);
    [fullResidual, details] = problem.evaluateWithInfo( ...
        unknown, p, q, context);
    % Full residual ordering is [dx,y,phi,dphi,BL,BLdot,BR,BRdot,
    % FL,FLdot,FR,FRdot,dy].  One equation from each left/right pair is
    % retained on Fix(left-right), yielding a square nine-dimensional chart.
    residual = fullResidual([1, 2, 3, 4, 5, 6, 9, 10, 13]);
    details.derivative_subspace = 'left-right-invariant';
    % HybridFiniteDifferenceJacobian_v3 compares cyclic and section
    % signatures.  Include the cluster partition in those differentiation
    % signatures so a persistent pair cluster cannot silently split while
    % retaining the same scalar event ordering.  The physical signatures
    % remain unchanged in details.map_info and in the explicitly named
    % fields below.
    details.physical_cyclic_event_signature = ...
        details.cyclic_event_signature;
    details.physical_section_relative_signature = ...
        details.section_relative_event_signature;
    details.hybrid_fd_event_cluster_signature = ...
        details.event_cluster_signature;
    details.cyclic_event_signature = sprintf('%s||clusters:%s', ...
        char(details.physical_cyclic_event_signature), ...
        char(details.event_cluster_signature));
    details.section_relative_event_signature = sprintf( ...
        '%s||clusters:%s', ...
        char(details.physical_section_relative_signature), ...
        char(details.event_cluster_signature));
end

