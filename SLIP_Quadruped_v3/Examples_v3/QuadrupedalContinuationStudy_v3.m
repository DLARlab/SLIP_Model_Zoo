function study = QuadrupedalContinuationStudy_v3(options)
%QUADRUPEDALCONTINUATIONSTUDY_V3 Reproducible Round-4 production study.
%   STUDY = QUADRUPEDALCONTINUATIONSTUDY_V3() uses only the event-driven
%   v3 map.  Event times and gait labels are observations, never unknowns.
%   The production seed has structural left/right simultaneous clusters;
%   root and Floquet derivatives are therefore formed on the left/right
%   invariant section chart and are labelled as symmetry restricted.
%
%   The saved artifact contains numerical summaries rather than MATLAB
%   handle objects, so it can be audited without reconstructing a session.

    if nargin < 1 || isempty(options)
        options = struct();
    end
    v3Root = fileparts(fileparts(mfilename('fullpath')));
    addStudyPaths(v3Root);
    defaults = defaultOptions(v3Root);
    options = mergeOptions(defaults, options);

    if options.ReuseSaved && isfile(options.SaveFile)
        saved = load(options.SaveFile, 'study');
        if isfield(saved, 'study')
            study = saved.study;
            if options.ResumePhysicalSearch
                study = resumePhysicalSearch(study, options);
            end
            return
        end
    end

    totalTimer = tic;
    study = struct();
    study.study_name = 'Round4 actual quadruped production validation';
    study.executed_at = char(datetime('now', 'TimeZone', 'local', ...
        'Format', 'yyyy-MM-dd HH:mm:ss Z'));
    study.matlab_version = version;
    study.platform = computer;
    study.options = options;
    study.model = 'Quadrupedal_Dynamics_v3';
    study.return_policy = 'EventCycleReturnPolicy_v3';
    study.prescribed_event_times = false;
    study.prescribed_gait_label = false;

    [baseOrbit, baseReport, framework] = QuadrupedalExample_v3(struct( ...
        'FixtureFile', options.FixtureFile, ...
        'FixtureColumn', options.FixtureColumn, ...
        'LegacyParameterPolicy', options.LegacyParameterPolicy, ...
        'Refine', false));
    schema = framework.schema;
    problem = framework.residual;
    baseUnknown = baseReport.converted_seed(:);
    baseParameter = baseOrbit.parameter(:);
    baseMode = baseOrbit.initial_mode;
    activeIndex = schema.parameterIndex(options.ActiveParameter);
    reducedBase = packLeftRightUnknown(baseUnknown);

    study.schema_metadata = schema.metadata();
    study.base = orbitSummary(baseOrbit, baseReport.residual_norm);
    study.base.fixture_path = baseReport.fixture_path;
    study.base.unknown = baseUnknown;
    study.base.reduced_unknown = reducedBase;
    study.base.parameter = baseParameter;
    study.base.mode = baseMode;
    study.base.is_event_discovered = true;
    study.base.has_structural_simultaneous_cluster = ...
        any(cellfun(@(members) numel(members) > 1, ...
        baseOrbit.event_cluster_members));
    saveStudyCheckpoint(study, options, 'base-constructed');

    reducedResidual = @(z, p, q, context) ...
        evaluateLeftRightResidual(z, p, q, problem, context);

    seedTimer = tic;
    study.asymmetric_seed_preparation = prepareAsymmetricSeed( ...
        reducedResidual, reducedBase, baseParameter, baseMode, ...
        activeIndex, options, problem);
    study.asymmetric_seed_preparation.elapsed_seconds = toc(seedTimer);
    saveStudyCheckpoint(study, options, 'asymmetric-seed-prepared');
    [validationSeed, validationParameter, validationMode] = ...
        selectPreparedSeed(study.asymmetric_seed_preparation, ...
        reducedBase, baseParameter, baseMode);

    simpleTimer = tic;
    study.simple_continuation = runSimpleContinuation( ...
        reducedResidual, validationSeed, validationParameter, ...
        validationMode, ...
        activeIndex, options, problem);
    study.simple_continuation.elapsed_seconds = toc(simpleTimer);
    saveStudyCheckpoint(study, options, 'simple-continuation-complete');

    [referenceReduced, referenceParameter, referenceMode] = ...
        selectAsymmetricReference(study.simple_continuation, ...
        validationSeed, validationParameter, validationMode, activeIndex);

    rootTimer = tic;
    study.default_hybrid_root = runDefaultHybridCorrection( ...
        reducedResidual, referenceReduced, referenceParameter, ...
        referenceMode, problem, options);
    study.default_hybrid_root.elapsed_seconds = toc(rootTimer);
    saveStudyCheckpoint(study, options, 'default-hybrid-root-complete');
    if study.default_hybrid_root.converged
        referenceReduced = study.default_hybrid_root.solution(:);
    end

    pseudoTimer = tic;
    study.pseudo_arclength = runPseudoArclength( ...
        reducedResidual, referenceReduced, referenceParameter, ...
        referenceMode, activeIndex, options, problem);
    study.pseudo_arclength.elapsed_seconds = toc(pseudoTimer);
    saveStudyCheckpoint(study, options, 'pseudo-arclength-complete');

    referenceUnknown = unpackLeftRightUnknown(referenceReduced);
    [~, referenceDetails] = problem.evaluateWithInfo( ...
        referenceUnknown, referenceParameter, referenceMode);
    referenceOrbit = problem.createOrbit(referenceUnknown, ...
        referenceParameter, referenceMode, referenceDetails);

    floquetTimer = tic;
    if options.RunFloquet
        study.floquet = runFloquetGridStudy( ...
            framework.map, referenceOrbit, schema, framework.simulator, ...
            options.FloquetStepGrids, options);
    else
        study.floquet = struct('attempted', false, 'status', 'not-run', ...
            'reason', 'RunFloquet=false');
    end
    study.floquet.elapsed_seconds = toc(floquetTimer);
    saveStudyCheckpoint(study, options, 'floquet-grid-study-complete');

    searchTimer = tic;
    if options.RunPhysicalSearch
        study.physical_search = runPhysicalSearch( ...
            problem, baseUnknown, baseParameter, baseMode, schema, options);
    else
        study.physical_search = emptyPhysicalSearch('RunPhysicalSearch=false');
    end
    study.physical_search.elapsed_seconds = toc(searchTimer);
    saveStudyCheckpoint(study, options, 'physical-search-complete');

    study.branch_switch_candidate_search = ...
        assessPhysicalBranchSwitchCandidates(study.floquet, ...
        referenceParameter(activeIndex), options);
    study.reference_orbit = orbitSummary(referenceOrbit, ...
        norm(referenceDetails.periodic_residual, inf));
    study.reference_orbit.parameter = referenceParameter;
    study.reference_orbit.mode = referenceMode;
    study.reference_orbit.unknown = referenceUnknown;
    study.total_elapsed_seconds = toc(totalTimer);
    study.completed = true;
    study.requirements = requirementSummary(study, options);

    saveStudyCheckpoint(study, options, 'complete');
end

function result = prepareAsymmetricSeed(residual, z0, p0, q0, ...
        activeIndex, options, problem)
    % This secant homotopy prepares a point safely separated from the
    % front/back simultaneous-cluster boundary.  Its points are explicitly
    % excluded from the validated production continuation count.
    result = struct('attempted', true, 'status', 'failed', ...
        'counted_as_validated_continuation', false, ...
        'derivative_model', 'forward-secant-seed-preparation-only', ...
        'accepted_count', 0, 'failure_count', 0, ...
        'requested_values', [], 'points', struct([]), ...
        'failures', struct([]), 'reason', '');
    values = p0(activeIndex) + linspace(0, ...
        options.SeedParameterOffset, options.SeedPreparationPointCount);
    result.requested_values = values;
    fd = FiniteDifferenceJacobian_v3(struct( ...
        'Method', 'forward', 'RelativeStep', options.SecantRelativeStep, ...
        'FailurePolicy', 'nan'));
    solver = RootSolver_v3(struct( ...
        'Jacobian', fd, 'Algorithm', 'newton', ...
        'FunctionTolerance', options.RootFunctionTolerance, ...
        'ResidualAcceptanceTolerance', options.RootAcceptanceTolerance, ...
        'MaxIterations', options.RootMaxIterations, ...
        'MaxFunctionEvaluations', options.RootMaxFunctionEvaluations));
    continuation = NumericalContinuation1D_v3(struct( ...
        'RootSolver', solver, 'ActiveParameterIndex', activeIndex, ...
        'StopOnFailure', true));
    try
        branch = continuation.run(residual, z0, p0, q0, values);
        result.accepted_count = branch.count;
        result.failure_count = numel(branch.failures);
        result.points = summarizeContinuationPoints( ...
            branch.points, problem, true);
        result.failures = summarizeContinuationPoints( ...
            branch.failures, problem, false);
        if branch.count == numel(values) && branch.success
            result.status = 'prepared';
        else
            result.reason = sprintf('Prepared %d of %d seed points.', ...
                branch.count, numel(values));
        end
    catch exception
        result.reason = exceptionReport(exception);
    end
end

function [z, p, q] = selectPreparedSeed(preparation, z0, p0, q0)
    z = z0;
    p = p0;
    q = q0;
    if isfield(preparation, 'points') && ~isempty(preparation.points)
        accepted = find([preparation.points.converged], 1, 'last');
        if ~isempty(accepted)
            point = preparation.points(accepted);
            z = point.reduced_unknown(:);
            p = point.parameter(:);
            q = point.mode;
        end
    end
end

function result = runSimpleContinuation(residual, z0, p0, q0, ...
        activeIndex, options, problem)
    result = struct('attempted', true, 'status', 'failed', ...
        'derivative_model', ...
            'left-right-symmetry-restricted-hybrid-classical', ...
        'active_parameter', options.ActiveParameter, ...
        'active_parameter_index', activeIndex, 'requested_values', [], ...
        'accepted_count', 0, 'failure_count', 0, 'points', struct([]), ...
        'failures', struct([]), 'topology_compatible', false, ...
        'cyclic_signatures', {{}}, 'section_signatures', {{}}, ...
        'cluster_signatures', {{}}, 'reason', '');
    values = p0(activeIndex) + linspace( ...
        options.SimpleParameterOffset(1), ...
        options.SimpleParameterOffset(2), options.SimplePointCount);
    result.requested_values = values;
    fd = continuationHybridJacobian(options);
    solver = RootSolver_v3(struct( ...
        'Jacobian', fd, 'Algorithm', 'newton', ...
        'FunctionTolerance', options.RootFunctionTolerance, ...
        'ResidualAcceptanceTolerance', options.RootAcceptanceTolerance, ...
        'MaxIterations', options.RootMaxIterations, ...
        'MaxFunctionEvaluations', options.RootMaxFunctionEvaluations));
    continuation = NumericalContinuation1D_v3(struct( ...
        'RootSolver', solver, 'ActiveParameterIndex', activeIndex, ...
        'StopOnFailure', true));
    try
        branch = continuation.run(residual, z0, p0, q0, values);
        result.accepted_count = branch.count;
        result.failure_count = numel(branch.failures);
        result.points = summarizeContinuationPoints( ...
            branch.points, problem, true);
        result.failures = summarizeContinuationPoints( ...
            branch.failures, problem, false);
        result = attachTopologyAudit(result);
        if branch.count >= options.SimplePointCount && branch.success && ...
                result.topology_compatible
            result.status = 'passed';
        else
            result.reason = sprintf( ...
                ['Accepted %d of %d requested points; topology ', ...
                 'compatible=%d.'], branch.count, ...
                options.SimplePointCount, result.topology_compatible);
        end
    catch exception
        result.reason = exceptionReport(exception);
    end
end

function result = runDefaultHybridCorrection(residual, zReference, ...
        pReference, qReference, problem, options)
    result = struct('attempted', true, 'status', 'failed', ...
        'converged', false, ...
        'derivative_model', ...
            'left-right-symmetry-restricted-hybrid-classical', ...
        'jacobian_class', 'HybridFiniteDifferenceJacobian_v3', ...
        'initial_guess', [], 'solution', [], 'initial_residual_norm', NaN, ...
        'final_residual_norm', Inf, 'map_evaluations', 0, ...
        'function_evaluations', 0, 'cache_hits', 0, ...
        'jacobian_evaluations', 0, 'accepted_newton_iterations', 0, ...
        'invalid_trial_count', 0, 'selected_steps', [], ...
        'estimated_column_errors', [], 'per_column_reliability', [], ...
        'event_cluster_signature', '', 'section_relative_signature', '', ...
        'cyclic_signature', '', 'mode_candidates', {{}}, 'reason', '');
    result.constructed_without_jacobian_override = true;
    perturbation = options.RootCorrectionPerturbation(:);
    if isscalar(perturbation)
        perturbation = perturbation .* defaultRootDirection(numel(zReference));
    end
    if numel(perturbation) ~= numel(zReference)
        error('QuadrupedalContinuationStudy_v3:RootPerturbation', ...
            'RootCorrectionPerturbation must be scalar or match the reduced chart.');
    end
    initialGuess = zReference(:) + perturbation;
    result.initial_guess = initialGuess;
    try
        [r0, initialInfo] = residual( ...
            initialGuess, pReference, qReference, struct());
        result.initial_residual_norm = norm(r0, inf);
        % Deliberately omit the Jacobian option.  This is the production
        % regression for RootSolver_v3's default hybrid differentiator.
        solver = RootSolver_v3(struct( ...
            'Algorithm', 'newton', ...
            'FunctionTolerance', options.RootFunctionTolerance, ...
            'ResidualAcceptanceTolerance', options.RootAcceptanceTolerance, ...
            'MaxIterations', options.RootMaxIterations, ...
            'MaxFunctionEvaluations', options.RootMaxFunctionEvaluations));
        [solution, solveInfo] = solver.solve( ...
            residual, initialGuess, pReference, qReference);
        result.solution = solution;
        result.converged = solveInfo.converged;
        result.status = ternary(solveInfo.converged, 'passed', 'failed');
        result.final_residual_norm = solveInfo.residualNorm;
        result.map_evaluations = solveInfo.mapEvaluationCount;
        result.function_evaluations = solveInfo.functionEvaluationCount;
        result.cache_hits = solveInfo.cacheHitCount;
        result.jacobian_evaluations = solveInfo.jacobianEvaluationCount;
        result.mode_candidates = solveInfo.candidateModes;
        result.invalid_trial_count = solveInfo.invalidEvaluationCount;
        output = memberOr(solveInfo, 'output', struct());
        result.accepted_newton_iterations = memberOr( ...
            output, 'acceptedIterations', 0);
        result.invalid_trial_count = max(result.invalid_trial_count, ...
            memberOr(output, 'invalidTrialCount', 0));
        jacobianInfo = memberOr(output, 'jacobianInfo', struct());
        result.selected_steps = memberOr(jacobianInfo, ...
            'selectedSteps', []);
        result.estimated_column_errors = memberOr(jacobianInfo, ...
            'estimatedErrors', []);
        result.per_column_reliability = memberOr(jacobianInfo, ...
            'perColumnReliability', []);
        result.jacobian_class = class(solver.Jacobian);
        if isstruct(initialInfo)
            result.initial_event_cluster_signature = memberOr( ...
                initialInfo, 'event_cluster_signature', '');
        end
        if isstruct(solveInfo.evaluationInfo)
            details = solveInfo.evaluationInfo;
            result.event_cluster_signature = memberOr( ...
                details, 'event_cluster_signature', '');
            mapInfo = memberOr(details, 'map_info', struct());
            result.section_relative_signature = memberOr(mapInfo, ...
                'section_relative_event_signature', memberOr(details, ...
                'physical_section_relative_signature', ''));
            result.cyclic_signature = memberOr(mapInfo, ...
                'cyclic_event_signature', memberOr(details, ...
                'physical_cyclic_event_signature', ''));
        end
        if ~solveInfo.converged
            result.reason = solveInfo.message;
        else
            unknown = unpackLeftRightUnknown(solution);
            [residualCheck, details] = problem.evaluateWithInfo( ...
                unknown, pReference, solveInfo.mode);
            result.full_residual_norm = norm(residualCheck, inf);
            result.cycle_complete = details.cycle_complete;
            result.physically_admissible = details.admissible;
        end
    catch exception
        result.reason = exceptionReport(exception);
    end
end

function result = runPseudoArclength(residual, z0, p0, q0, ...
        activeIndex, options, problem)
    result = struct('attempted', true, 'status', 'failed', ...
        'derivative_model', ...
            'left-right-symmetry-restricted-hybrid-classical', ...
        'active_parameter', options.ActiveParameter, ...
        'active_parameter_index', activeIndex, 'accepted_count', 0, ...
        'failure_count', 0, 'points', struct([]), ...
        'failures', struct([]), 'termination_reason', '', ...
        'topology_compatible', false, 'cyclic_signatures', {{}}, ...
        'section_signatures', {{}}, 'cluster_signatures', {{}}, ...
        'reason', '');
    fd = continuationHybridJacobian(options);
    solver = RootSolver_v3(struct( ...
        'Jacobian', fd, 'Algorithm', 'newton', ...
        'FunctionTolerance', options.RootFunctionTolerance, ...
        'ResidualAcceptanceTolerance', options.RootAcceptanceTolerance, ...
        'MaxIterations', options.RootMaxIterations, ...
        'MaxFunctionEvaluations', options.RootMaxFunctionEvaluations));
    continuation = PseudoArclengthContinuation_v3(struct( ...
        'RootSolver', solver, 'Jacobian', fd, ...
        'ActiveParameterIndex', activeIndex, ...
        'StepSize', options.PseudoStepSize, ...
        'MinimumStepSize', options.PseudoMinimumStepSize, ...
        'MaximumStepSize', options.PseudoMaximumStepSize, ...
        'MaxPoints', options.PseudoPointCount, ...
        'ParameterBounds', p0(activeIndex) + options.PseudoParameterBounds, ...
        'InitialDirection', sign(options.PseudoStepSize), ...
        'ReuseCorrectorJacobian', false));
    try
        branch = continuation.run(residual, z0, p0, q0);
        result.accepted_count = branch.count;
        result.failure_count = numel(branch.failures);
        result.termination_reason = branch.terminationReason;
        result.points = summarizeContinuationPoints( ...
            branch.points, problem, true);
        result.failures = summarizeContinuationPoints( ...
            branch.failures, problem, false);
        result = attachTopologyAudit(result);
        if branch.count >= options.PseudoPointCount && ...
                result.topology_compatible
            result.status = 'passed';
        else
            result.reason = sprintf( ...
                ['Accepted %d of %d requested points (%s); topology ', ...
                 'compatible=%d.'], ...
                branch.count, options.PseudoPointCount, ...
                branch.terminationReason, result.topology_compatible);
        end
    catch exception
        result.reason = exceptionReport(exception);
    end
end

function result = runFloquetGridStudy(map, orbit, schema, simulator, ...
        stepGrids, options)
    result = struct('attempted', true, 'status', 'failed', ...
        'derivative_model', 'left-right-symmetry-restricted-classical', ...
        'step_grids', {stepGrids}, 'grid_results', struct([]), ...
        'matrix_differences', [], 'matched_multiplier_differences', [], ...
        'converged', false, 'reason', '');
    subspace = SymmetrySubspace_v3.quadrupedSectionTangent(schema);
    entries = repmat(emptyFloquetGrid(), 1, numel(stepGrids));
    rawMatrices = cell(1, numel(stepGrids));
    rawMultipliers = cell(1, numel(stepGrids));
    for index = 1:numel(stepGrids)
        grid = stepGrids{index};
        try
            fd = HybridFiniteDifferenceJacobian_v3(struct( ...
                'RelativeCandidateSteps', grid, ...
                'MaximumRelativeError', options.HybridMaximumRelativeError, ...
                'RequireCompatibleCyclicSignature', true, ...
                'RequireCompatibleSectionSignature', true, ...
                'FailurePolicy', 'nan'));
            baseAnalyzer = FloquetAnalysis_v3(struct( ...
                'Jacobian', fd, 'ComputeAmbientJacobian', false, ...
                'RequireCompatibleSectionSignature', true, ...
                'RequireMatchingEventSignature', true));
            analyzer = SymmetryRestrictedFloquet_v3(subspace, struct( ...
                'Analyzer', baseAnalyzer, ...
                'BlockName', 'left-right-invariant-section', ...
                'RequireClusterPreservation', true));
            value = analyzer.analyze(map, orbit.initial_state, ...
                orbit.initial_mode, orbit.parameter);
            entries(index) = summarizeFloquet(value, grid, simulator);
            rawMatrices{index} = value.poincareMatrix;
            rawMultipliers{index} = value.multipliers;
        catch exception
            entries(index).step_grid = grid;
            entries(index).reason = exceptionReport(exception);
        end
    end
    result.grid_results = entries;
    differences = NaN(1, max(0, numel(entries) - 1));
    multiplierDifferences = differences;
    for index = 1:numel(differences)
        if ~isempty(rawMatrices{index}) && ~isempty(rawMatrices{index + 1})
            differences(index) = norm( ...
                rawMatrices{index} - rawMatrices{index + 1}, 'fro');
            multiplierDifferences(index) = matchedMultiplierDistance( ...
                rawMultipliers{index}, rawMultipliers{index + 1});
        end
    end
    result.matrix_differences = differences;
    result.matched_multiplier_differences = multiplierDifferences;
    reliable = [entries.reliable];
    finiteComparisons = all(isfinite(differences)) && ...
        all(isfinite(multiplierDifferences));
    fineMatrix = isempty(differences) || ...
        differences(end) <= options.FloquetMatrixConvergenceTolerance;
    fineMultipliers = isempty(multiplierDifferences) || ...
        multiplierDifferences(end) <= ...
        options.FloquetMultiplierConvergenceTolerance;
    result.converged = all(reliable) && finiteComparisons && ...
        fineMatrix && fineMultipliers;
    if result.converged
        result.status = 'passed';
    else
        result.reason = sprintf( ...
            'reliable=%s, matrix differences=%s, multiplier differences=%s', ...
            mat2str(reliable), mat2str(differences, 5), ...
            mat2str(multiplierDifferences, 5));
    end
end

function study = resumePhysicalSearch(study, options)
    timer = tic;
    [~, ~, framework] = QuadrupedalExample_v3(struct( ...
        'FixtureFile', options.FixtureFile, ...
        'FixtureColumn', options.FixtureColumn, ...
        'LegacyParameterPolicy', options.LegacyParameterPolicy, ...
        'Refine', false));
    reference = study.reference_orbit;
    study.physical_search = runPhysicalSearch( ...
        framework.residual, reference.unknown, reference.parameter, ...
        reference.mode, framework.schema, options);
    study.physical_search.elapsed_seconds = toc(timer);
    study.requirements = requirementSummary(study, options);
    study.total_elapsed_seconds = study.total_elapsed_seconds + ...
        study.physical_search.elapsed_seconds;
    saveStudyCheckpoint(study, options, 'physical-search-resumed');
end

function search = runPhysicalSearch(problem, u0, p0, q0, schema, options)
    search = emptyPhysicalSearch('');
    search.attempted = true;
    search.status = 'completed-no-requested-case-found';
    definitions = physicalSearchDefinitions(p0, schema, options);
    search.parameter_ranges = definitions;
    search.seed_unknown = u0;
    search.seed_parameter = p0;
    search.seed_mode = q0;
    search.derivative_model = ...
        'topology-aware-unrestricted-hybrid-classical-or-rejected';
    search.outcomes = repmat(struct('parameter_name', '', ...
        'requested_values', [], 'accepted_count', 0, 'failure_count', 0, ...
        'points', struct([]), 'failures', struct([]), 'reason', ''), ...
        1, numel(definitions));

    fd = continuationHybridJacobian(options);
    solver = RootSolver_v3(struct( ...
        'Jacobian', fd, 'Algorithm', 'newton', ...
        'FunctionTolerance', options.RootFunctionTolerance, ...
        'ResidualAcceptanceTolerance', options.RootAcceptanceTolerance, ...
        'MaxIterations', options.SearchMaxIterations, ...
        'MaxFunctionEvaluations', options.RootMaxFunctionEvaluations));
    searchResidual = fullClusterResidualInterface(problem);
    observations = struct([]);
    for definitionIndex = 1:numel(definitions)
        definition = definitions(definitionIndex);
        continuation = NumericalContinuation1D_v3(struct( ...
            'RootSolver', solver, ...
            'ActiveParameterIndex', definition.parameter_index, ...
            'StopOnFailure', false));
        outcome = search.outcomes(definitionIndex);
        outcome.parameter_name = definition.parameter_name;
        outcome.requested_values = definition.values;
        try
            branch = continuation.run(searchResidual, u0, p0, q0, ...
                definition.values);
            outcome.accepted_count = branch.count;
            outcome.failure_count = numel(branch.failures);
            outcome.points = summarizeContinuationPoints( ...
                branch.points, problem, true);
            outcome.failures = summarizeContinuationPoints( ...
                branch.failures, problem, false);
            observations = [observations, outcome.points]; %#ok<AGROW>
        catch exception
            outcome.reason = exceptionReport(exception);
        end
        search.outcomes(definitionIndex) = outcome;
    end
    search.observations = observations;
    search.accepted_orbit_count = numel(observations);
    search.rejection_count = sum([search.outcomes.failure_count]);
    search.rejection_causes = collectRejectionCauses(search.outcomes);
    search.non_simultaneous_orbit_search = runNonSimultaneousSearch( ...
        searchResidual, problem, u0, p0, q0, options);
    search.found_non_simultaneous_orbit = ...
        search.non_simultaneous_orbit_search.found;

    search.grounded_apex = firstObservation(observations, ...
        @(point) point.converged && any(logical(point.mode(:))));
    search.multiple_apex = firstObservation(observations, ...
        @(point) point.converged && point.candidate_apex_count >= 2 && ...
            point.accepted_apex_index >= 2);
    search.section_mode_transition = detectSectionModeTransition( ...
        search.outcomes, options.SectionCoincidenceTolerance);
    search.found_grounded_apex = ~isempty(search.grounded_apex);
    search.multiple_apex_policy_comparison = struct( ...
        'attempted', false, 'validated', false, ...
        'first_return_is_intermediate', false, ...
        'event_cycle_returns_full_cycle', false, ...
        'reason', 'No validated multiple-apex candidate was found.');
    if ~isempty(search.multiple_apex)
        search.multiple_apex_policy_comparison = ...
            compareMultipleApexPolicies(problem, search.multiple_apex);
    end
    search.found_multiple_apex = ...
        search.multiple_apex_policy_comparison.validated;
    search.found_section_mode_transition = ...
        search.section_mode_transition.found;
    search.refined_section_coincidence = ...
        search.section_mode_transition.found && ...
        search.section_mode_transition.exact_coincidence;
    if search.found_grounded_apex || search.found_multiple_apex || ...
            search.found_section_mode_transition
        search.status = 'completed-one-or-more-cases-found';
    end
end

function search = runNonSimultaneousSearch( ...
        residual, problem, u0, p0, q0, options)
    search = struct('attempted', true, 'found', false, ...
        'derivative_model', ...
            'unrestricted-topology-aware-hybrid-classical-or-rejected', ...
        'amplitudes', options.NonSimultaneousSearchAmplitudes, ...
        'direction_names', {{'paired-angle-antisymmetry', ...
            'crossed-angle-antisymmetry'}}, ...
        'attempts', struct([]), ...
        'reason', 'No validated non-simultaneous orbit was found.');
    directions = zeros(13, 2);
    directions([6, 8, 10, 12], 1) = [1, -1, 1, -1];
    directions([6, 8, 10, 12], 2) = [1, -1, -1, 1];
    attempts = repmat(struct('amplitude', NaN, 'direction_name', '', ...
        'initial_residual_norm', Inf, 'initial_cluster_signature', '', ...
        'converged', false, 'final_residual_norm', Inf, ...
        'physically_admissible', false, ...
        'all_event_clusters_singleton', false, ...
        'event_cluster_signature', '', 'map_evaluations', 0, ...
        'jacobian_evaluations', 0, 'accepted_iterations', 0, ...
        'failure_reason', ''), 1, 0);
    fd = continuationHybridJacobian(options);
    for directionIndex = 1:size(directions, 2)
        direction = directions(:, directionIndex);
        direction = direction / norm(direction);
        for amplitude = options.NonSimultaneousSearchAmplitudes(:).'
            record = attemptsTemplate();
            record.amplitude = amplitude;
            record.direction_name = search.direction_names{directionIndex};
            guess = u0(:) + amplitude .* direction;
            try
                [initialResidual, initialDetails] = ...
                    residual.evaluateWithInfo(guess, p0, q0, struct());
                record.initial_residual_norm = norm(initialResidual, inf);
                record.initial_cluster_signature = memberOr( ...
                    initialDetails, 'event_cluster_signature', '');
                solver = RootSolver_v3(struct( ...
                    'Jacobian', fd, 'Algorithm', 'newton', ...
                    'FunctionTolerance', options.RootFunctionTolerance, ...
                    'ResidualAcceptanceTolerance', ...
                        options.RootAcceptanceTolerance, ...
                    'MaxIterations', options.NonSimultaneousSearchMaxIterations, ...
                    'MaxFunctionEvaluations', ...
                        options.RootMaxFunctionEvaluations));
                [solution, info] = solver.solve( ...
                    residual, guess, p0, q0);
                record.converged = info.converged;
                record.final_residual_norm = info.residualNorm;
                record.map_evaluations = info.mapEvaluationCount;
                record.jacobian_evaluations = info.jacobianEvaluationCount;
                record.accepted_iterations = memberOr( ...
                    info.output, 'acceptedIterations', 0);
                if info.converged
                    [~, details] = problem.evaluateWithInfo( ...
                        solution, p0, info.mode);
                    record.physically_admissible = details.admissible;
                    record.event_cluster_signature = ...
                        details.event_cluster_signature;
                    clusters = details.event_clusters;
                    record.all_event_clusters_singleton = ...
                        ~isempty(clusters) && all(arrayfun( ...
                        @(cluster) isscalar(cluster.names), clusters));
                    if record.physically_admissible && ...
                            record.all_event_clusters_singleton && ...
                            info.residualNorm <= options.RootAcceptanceTolerance
                        search.found = true;
                        search.solution = solution;
                        search.mode = info.mode;
                    end
                else
                    record.failure_reason = info.message;
                end
            catch exception
                record.failure_reason = exceptionReport(exception);
            end
            attempts(end + 1) = record; %#ok<AGROW>
        end
    end
    search.attempts = attempts;
    if search.found
        search.reason = '';
    end
end

