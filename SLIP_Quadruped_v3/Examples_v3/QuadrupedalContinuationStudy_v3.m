function transition = detectSectionModeTransition(outcomes, tolerance)
    transition = struct('found', false, 'parameter_name', '', ...
        'left_point', struct(), 'right_point', struct(), ...
        'event_name', '', 'bracket', [], 'exact_coincidence', false, ...
        'reason', 'No accepted neighboring section charts changed mode.');
    for outcomeIndex = 1:numel(outcomes)
        points = outcomes(outcomeIndex).points;
        for pointIndex = 2:numel(points)
            left = points(pointIndex - 1);
            right = points(pointIndex);
            if ~left.converged || ~right.converged || ...
                    isequal(logical(left.mode(:)), logical(right.mode(:)))
                continue
            end
            [eventName, signedLeft, signedRight] = ...
                crossingEvent(left, right);
            if isempty(eventName)
                continue
            end
            transition.found = true;
            transition.parameter_name = outcomes(outcomeIndex).parameter_name;
            transition.left_point = left;
            transition.right_point = right;
            transition.event_name = eventName;
            parameterIndex = find(left.parameter ~= right.parameter, 1);
            if isempty(parameterIndex)
                transition.bracket = [];
            else
                transition.bracket = [left.parameter(parameterIndex), ...
                    right.parameter(parameterIndex)];
            end
            transition.signed_event_phase = [signedLeft, signedRight];
            transition.exact_coincidence = ...
                left.section_cluster_coincidence || ...
                right.section_cluster_coincidence || ...
                min(abs([signedLeft, signedRight])) <= tolerance;
            transition.reason = '';
            return
        end
    end
end

function comparison = compareMultipleApexPolicies(problem, point)
    comparison = struct('attempted', true, 'validated', false, ...
        'first_return_is_intermediate', false, ...
        'event_cycle_returns_full_cycle', false, ...
        'first_return_period', NaN, 'event_cycle_period', NaN, ...
        'first_return_candidate_index', NaN, ...
        'event_cycle_accepted_index', NaN, 'reason', '');
    try
        cycleMap = problem.Map;
        firstMap = PoincareMap_v3( ...
            cycleMap.System, cycleMap.Section, cycleMap.Simulator, ...
            FirstReturnPolicy_v3(), struct( ...
                'ModeResolver', cycleMap.ModeResolver, ...
                'MaxReturnTime', cycleMap.MaxReturnTime, ...
                'MaxSectionCrossings', cycleMap.MaxSectionCrossings, ...
                'MaxCycleEvents', cycleMap.MaxCycleEvents, ...
                'ArmTolerance', cycleMap.ArmTolerance, ...
                'InitialTime', cycleMap.InitialTime));
        state = problem.fullState(point.full_unknown);
        [~, firstInfo] = firstMap.evaluate( ...
            state, point.mode, point.parameter);
        [~, cycleInfo] = cycleMap.evaluate( ...
            state, point.mode, point.parameter);
        comparison.first_return_period = firstInfo.period;
        comparison.event_cycle_period = cycleInfo.period;
        comparison.first_return_candidate_index = ...
            firstInfo.accepted_crossing_index;
        comparison.event_cycle_accepted_index = ...
            cycleInfo.accepted_crossing_index;
        comparison.first_return_is_intermediate = ...
            firstInfo.accepted_crossing_index == 1 && ...
            firstInfo.period < cycleInfo.period && ...
            cycleInfo.accepted_crossing_index >= 2;
        comparison.event_cycle_returns_full_cycle = ...
            cycleInfo.cycle_complete && ...
            cycleInfo.return_policy_accepted;
        comparison.validated = ...
            comparison.first_return_is_intermediate && ...
            comparison.event_cycle_returns_full_cycle;
        if ~comparison.validated
            comparison.reason = ['The two policies did not establish an ', ...
                'intermediate first apex and a completed later cycle.'];
        end
    catch exception
        comparison.reason = exceptionReport(exception);
    end
end

function [name, leftPhase, rightPhase] = crossingEvent(left, right)
    name = '';
    leftPhase = NaN;
    rightPhase = NaN;
    leftNames = {left.circular_event_phase.name};
    rightNames = {right.circular_event_phase.name};
    common = intersect(leftNames, rightNames, 'stable');
    for index = 1:numel(common)
        leftEntry = left.circular_event_phase(strcmp(leftNames, common{index}));
        rightEntry = right.circular_event_phase(strcmp(rightNames, common{index}));
        if leftEntry.signed_time * rightEntry.signed_time <= 0
            name = common{index};
            leftPhase = leftEntry.signed_time;
            rightPhase = rightEntry.signed_time;
            return
        end
    end
end

function phases = circularEventPhase(history, period)
    phases = repmat(struct('name', '', 'time', NaN, ...
        'phase', NaN, 'signed_time', NaN), 1, numel(history));
    if ~(isscalar(period) && isfinite(period) && period > 0)
        return
    end
    for index = 1:numel(history)
        time = memberOr(history(index), 'time', NaN);
        phase = time / period;
        phases(index).name = char(memberOr(history(index), 'type', ''));
        phases(index).time = time;
        phases(index).phase = phase;
        phases(index).signed_time = ...
            (mod(phase + 0.5, 1) - 0.5) * period;
    end
end

