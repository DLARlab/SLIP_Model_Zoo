function result = mergeOptions(defaults, supplied)
    if ~isstruct(supplied) || ~isscalar(supplied)
        error('QuadrupedalContinuationStudy_v3:Options', ...
            'Options must be a scalar structure.');
    end
    result = defaults;
    names = fieldnames(supplied);
    for index = 1:numel(names)
        if ~isfield(defaults, names{index})
            error('QuadrupedalContinuationStudy_v3:UnknownOption', ...
                'Unknown option "%s".', names{index});
        end
        result.(names{index}) = supplied.(names{index});
    end
end

function value = memberOr(source, name, fallback)
    value = fallback;
    if isstruct(source) && isfield(source, name)
        value = source.(name);
    elseif isobject(source) && isprop(source, name)
        value = source.(name);
    end
end

function value = ternary(condition, yes, no)
    if condition
        value = yes;
    else
        value = no;
    end
end

