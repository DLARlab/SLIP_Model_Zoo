function report = TouchdownDiagnostics_v3(system,descriptor,time,xminus,xplus,qminus,qplus,p,tolerance)
%TOUCHDOWNDIAGNOSTICS_V3 Observe the existing native contact reset.
% This report does not accept/reject a state or change any contact law.
% The identity gdot+=cos(theta)*rdot+ is evaluated on the TD surface.
    report=struct([]);
    if ~isa(system,'Quadrupedal_Dynamics_v3')||~isfield(descriptor,'kind') ...
            ||~strcmpi(string(descriptor.kind),'touchdown')
        return
    end
    if nargin<9||isempty(tolerance),tolerance=1e-10;end
    schema=system.Schema;leg=descriptor.leg_index;state=schema.State;
    expanded=schema.expandParameters(p);offset=expanded.s(leg);
    theta=xplus(state.phi)+xplus(schema.Leg.AngleIndices(leg));
    hipVx=xplus(state.dx)-offset*sin(xplus(state.phi))*xplus(state.dphi);
    hipVy=xplus(state.dy)+offset*cos(xplus(state.phi))*xplus(state.dphi);
    radial=hipVy*cos(theta)-hipVx*sin(theta);
    outgoing=cos(theta)*radial;
    nativeSlopes=system.GuardFunctionsComponent.legDirectionalDerivatives(xplus,p);
    guards=system.GuardFunctionsComponent.legValues(xplus,p);
    expectedRate=system.ResetMapComponent.projectedAngularRate(xminus,leg,p);
    rateError=abs(xplus(schema.Leg.RateIndices(leg))-expectedRate);
    unchanged=setdiff(1:schema.StateDimension,schema.Leg.RateIndices(leg));
    % A batch can reset another leg rate. Only the torso/angle coordinates
    % are required unchanged by this scalar diagnostic.
    unchanged=setdiff(unchanged,schema.Leg.RateIndices);
    stateError=max(abs(xplus(unchanged)-xminus(unchanged)));
    modeConsistent=~qminus(leg)&&qplus(leg);
    scale=max(1,norm([xminus(:);xplus(:)],inf));
    resetTolerance=256*eps(scale);
    report=struct('schema_version','native-touchdown-diagnostics-v3-1', ...
        'time',time,'event_id',descriptor.id,'leg_index',leg, ...
        'leg_name',schema.Leg.Names{leg},'absolute_leg_angle',theta, ...
        'incoming_guard_slope',descriptor.directional_derivative, ...
        'post_reset_radial_length_rate',radial, ...
        'post_reset_guard_slope',outgoing, ...
        'native_post_reset_guard_slope',nativeSlopes(leg), ...
        'post_reset_guard_slope_consistency_error',abs(outgoing-nativeSlopes(leg)), ...
        'guard_surface_error',abs(guards(leg)), ...
        'projected_angular_rate_error',rateError, ...
        'continuous_coordinates_reset_error',stateError, ...
        'mode_transition_consistent',modeConsistent, ...
        'reset_consistency_tolerance',resetTolerance, ...
        'reset_consistent',modeConsistent&&rateError<=resetTolerance&&stateError<=resetTolerance, ...
        'outward_rate_resolution',tolerance, ...
        'strict_outward_post_reset',radial>tolerance, ...
        'radial_rate_unresolved',abs(radial)<=tolerance, ...
        'scope','Kinematic observation at the contact; grazing/equality cases require higher-order analysis.');
end
