function [results, flags, info] = FakeContinuation(z1, z2, Para, ~, ~, ~)
    z3 = z2 + 0.5 * (z2 - z1);
    results = [[z1; Para], [z2; Para], [z3; Para]];
    flags = ["fixture complete", "fixture complete"];
    info = struct('fixture', true);
end

function [results, flags, info] = FakeFivePointContinuation( ...
        z1, z2, Para, ~, ~, ~)
    increment = z2 - z1;
    points = [z1, z2, z2 + increment, z2 + 2 * increment, ...
        z2 + 3 * increment];
    results = [points; repmat(Para, 1, size(points, 2))];
    flags = ["fixture complete", "fixture complete"];
    info = struct('fixture', true);
end


function [results, flags, info] = FakeOrthogonalContinuation(z1, ~, Para, ~, ~, ~)
    base = z1;
    base(1) = 0;
    points = repmat(base, 1, 3);
    points(2, :) = base(2) + [0.01 0.02 0.03];
    results = [points; repmat(Para, 1, 3)];
    flags = ["fixture left ray", "fixture left ray"];
    info = struct('fixture', true);
end


function [results, flags, info] = FakeDuplicateContinuation(z1, z2, Para, ~, ~, ~)
    results = [[z1; Para], [z2; Para], [z2; Para]];
    flags = ["fixture duplicate", "fixture duplicate"];
    info = struct('fixture', true);
end

function report = FakeValidationWithoutTopology(~, ~, ~)
    report = struct('accepted', true, 'status', 'accepted', ...
        'rejectionReasons', {{}}, 'periodicResidualNormInf', 0, ...
        'mapInfo', struct('timingResidualNormInf', 0));
end

function report = FakeAcceptedValidation(solution, ~, options)
    topology = floquet.internal.events.classifyTopology( ...
        solution(14:22), options);
    report = struct('accepted', true, 'status', 'accepted', ...
        'rejectionReasons', {{}}, 'periodicResidualNormInf', 0, ...
        'mapInfo', struct('timingResidualNormInf', 0, ...
            'eventTopology', topology));
end

function report = FakeSeedTopologyOnlyValidation(solution, ~, options)
    report = FakeAcceptedValidation(solution, [], options);
    if solution(1) > 0.0201
        report.mapInfo = rmfield(report.mapInfo, 'eventTopology');
    end
end

function report = FakeChangedOutputTopologyValidation(solution, ~, options)
    report = FakeAcceptedValidation(solution, [], options);
    if solution(1) > 0.0201
        topology = report.mapInfo.eventTopology;
        labels = topology.sortedEventNumbers([1 2]);
        topology.normalizedPhases(labels) = ...
            topology.normalizedPhases(labels([2 1]));
        topology.sortedEventNumbers([1 2]) = ...
            topology.sortedEventNumbers([2 1]);
        topology.signature = ['changed: ' topology.signature];
        report.mapInfo.eventTopology = topology;
    end
end
