function testTwoSameRaySeedsAreForwarded(testCase)
    [critical, direction, seed1, seed2, parameters] = Fixture();
    options = struct('CriticalSolution', critical, ...
        'Direction', direction, 'ValidateSeeds', false, ...
        'ValidateOutput', false, ...
        'RequireConsistentOutputTopology', false, ...
        'MinimumOutputPoints', 3, ...
        'ContinuationFunction', @FakeContinuation);
    [results, info] = floquet.continueDaughterBranch( ...
        seed1, seed2, parameters, options);
    testCase.verifySize(results, [29 3]);
    testCase.verifyFalse(info.accepted);
    testCase.verifyEqual(info.status, ...
        'unvalidated-test-or-diagnostic-output');
    testCase.verifyFalse(info.validationEvidenceComplete);
    testCase.verifyTrue(info.rayGeometry.checked);
    testCase.verifyTrue(info.rayGeometry.sameRay);
    testCase.verifyGreaterThan(prod(info.rayGeometry.projection), 0);
    testCase.verifyTrue(info.daughterGeometry.checked);
    testCase.verifyGreaterThanOrEqual( ...
        info.daughterGeometry.sameRayAlignedCount, 3);
    testCase.verifyGreaterThanOrEqual( ...
        info.daughterGeometry.sameRayAlignedDistinctCount, 3);
    testCase.verifyGreaterThanOrEqual( ...
        info.daughterGeometry.maximumConsecutiveAlignedDistinctCount, 3);
end

