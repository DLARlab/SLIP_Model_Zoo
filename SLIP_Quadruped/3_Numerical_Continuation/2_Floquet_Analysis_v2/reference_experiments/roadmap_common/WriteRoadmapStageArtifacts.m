function files = WriteRoadmapStageArtifacts(report, paths)
%WRITEROADMAPSTAGEARTIFACTS Materialize one reference run by workflow stage.
%
% These are retrospective, targeted-window reference experiments. The
% emitted reference_experiment_config.mat states that distinction explicitly
% and is not presented as a resumable floquet.workflow.Session config.

    ValidateInputs(report, paths);
    stageDirectories = {paths.DiscoveryRoot, paths.RefinementRoot, ...
        paths.SeedSearchRoot, paths.DaughterBranchesRoot, ...
        paths.ValidationRoot, paths.CheckpointsRoot, paths.ViewsRoot, ...
        paths.LogRoot};
    for k = 1:numel(stageDirectories)
        EnsureDirectory(stageDirectories{k});
    end

    stamp = Timestamp();
    layout = 'numbered-artifacts-v1';
    transitionIDs = {report.transitions.ID};

    referenceConfig = struct( ...
        'SchemaVersion','floquet-reference-experiment-config-v2', ...
        'ArtifactLayoutVersion',layout, ...
        'ExperimentType','targeted-retrospective-reference', ...
        'ExperimentRoot',paths.ExperimentRoot, ...
        'TransitionIDs',{transitionIDs}, ...
        'ParentFiles',{unique({report.transitions.ParentFile},'stable')}, ...
        'HeldOutFiles',{unique({report.transitions.DaughterFile},'stable')}, ...
        'CreatedAt',stamp, ...
        'WorkflowCompatibility', ...
            'not-resumable-by-floquet.workflow.Session', ...
        'InformationBarrier',[ ...
            'Held-out daughter files enter only the validation stage; ' ...
            'the targeted parent scan windows are fixed in code.']);
    configFile = paths.ReferenceConfigFile;
    save(configFile,'referenceConfig','-v7');

    discoveryItems = repmat(struct('TransitionID','','ParentCode','', ...
        'DaughterCode','','Scan',struct(),'Candidate',struct()), ...
        1,numel(report.transitions));
    refinementItems = repmat(struct('TransitionID','', ...
        'CriticalSolution',[],'Refinement',struct(), ...
        'Symmetry',struct()),1,numel(report.transitions));
    seedItems = repmat(struct('TransitionID','','Attempts',struct([]), ...
        'SignPairSymmetry',struct()),1,numel(report.transitions));
    daughterItems = repmat(struct('TransitionID','', ...
        'AcceptedAttempts',struct([])),1,numel(report.transitions));
    for k = 1:numel(report.transitions)
        spec = report.transitions(k);
        analysis = report.analyses(k);
        discoveryItems(k).TransitionID = spec.ID;
        discoveryItems(k).ParentCode = spec.ParentCode;
        discoveryItems(k).DaughterCode = spec.DaughterCode;
        discoveryItems(k).Scan = FieldOr(analysis,'scan',struct());
        discoveryItems(k).Candidate = FieldOr(analysis,'candidate',struct());
        refinementItems(k).TransitionID = spec.ID;
        refinementItems(k).CriticalSolution = ...
            FieldOr(analysis,'criticalSolution',[]);
        refinementItems(k).Refinement = ...
            FieldOr(analysis,'refinement',struct());
        refinementItems(k).Symmetry = FieldOr(analysis,'symmetry',struct());
        seedItems(k).TransitionID = spec.ID;
        seedItems(k).Attempts = FieldOr(analysis,'attempts',struct([]));
        seedItems(k).SignPairSymmetry = ...
            FieldOr(analysis,'signPairSymmetry',struct());
        daughterItems(k).TransitionID = spec.ID;
        attempts = seedItems(k).Attempts;
        if ~isempty(attempts) && isfield(attempts,'acceptedBranchPoint')
            daughterItems(k).AcceptedAttempts = ...
                attempts(logical([attempts.acceptedBranchPoint]));
        end
    end

    discoveryReport = StageRecord('floquet-reference-discovery-v2', ...
        layout, stamp, discoveryItems);
    refinementReport = StageRecord('floquet-reference-refinement-v2', ...
        layout, stamp, refinementItems);
    seedReport = StageRecord('floquet-reference-seed-search-v2', ...
        layout, stamp, seedItems);
    daughterReport = StageRecord('floquet-reference-daughters-v2', ...
        layout, stamp, daughterItems);
    files = struct();
    files.Config = configFile;
    files.Discovery = fullfile(paths.DiscoveryRoot,'floquet_analysis.mat');
    files.Candidates = fullfile(paths.DiscoveryRoot, ...
        'candidate_inventory.csv');
    files.Refinement = fullfile(paths.RefinementRoot, ...
        'refined_candidates.mat');
    files.RefinementSummary = fullfile(paths.RefinementRoot, ...
        'refinement_summary.csv');
    files.Seeds = fullfile(paths.SeedSearchRoot, ...
        'daughter_seed_search.mat');
    files.SeedAttempts = fullfile(paths.SeedSearchRoot, ...
        'daughter_seed_attempts.csv');
    files.Daughters = fullfile(paths.DaughterBranchesRoot,'inventory.mat');
    files.DaughterInventory = fullfile(paths.DaughterBranchesRoot, ...
        'inventory.csv');
    files.Validation = fullfile(paths.ValidationRoot, ...
        'validation_report.mat');
    files.ValidationSummary = fullfile(paths.ValidationRoot, ...
        'validation_summary.csv');

    % These reference projections are ordinary MATLAB structures well below
    % the v7 size limit.  Compressed v7 avoids the severe small-object HDF5
    % overhead of v7.3 while preserving every numerical value.
    save(files.Discovery,'discoveryReport','-v7');
    save(files.Refinement,'refinementReport','-v7');
    save(files.Seeds,'seedReport','-v7');
    save(files.Daughters,'daughterReport','-v7');

    authoritativeFile = fullfile(paths.ValidationRoot, ...
        'roadmap_bifurcation_robustness_results.mat');
    validationPayload = CompactValidationIndex(report, paths, files, ...
        authoritativeFile);
    validationReport = StageRecord( ...
        'floquet-reference-validation-index-v3',layout,stamp, ...
        validationPayload);
    save(files.Validation,'validationReport','-v7');

    [candidateTable, refinementTable, seedTable, daughterTable, ...
        validationTable] = SummaryTables(report, daughterItems);
    writetable(candidateTable,files.Candidates);
    writetable(refinementTable,files.RefinementSummary);
    writetable(seedTable,files.SeedAttempts);
    writetable(daughterTable,files.DaughterInventory);
    writetable(validationTable,files.ValidationSummary);
end

function payload = CompactValidationIndex(report, paths, files, ...
        authoritativeFile)
%COMPACTVALIDATIONINDEX Retain Stage-5 evidence without copying Stages 1--4.
    if ~isfile(authoritativeFile)
        error('WriteRoadmapStageArtifacts:AuthoritativeResult', ...
            ['Save the authoritative roadmap result before materializing ' ...
             'the compact Stage-5 index: %s'],authoritativeFile);
    end

    count = numel(report.transitions);
    transitions = repmat(EmptyValidationSummary(),1,count);
    for k = 1:count
        spec = report.transitions(k);
        analysis = report.analyses(k);
        validation = report.validations(k);
        candidate = FieldOr(analysis,'candidate',struct());
        refinement = FieldOr(analysis,'refinement',struct());
        multiplier = FieldOr(refinement,'multiplier',NaN);

        transitions(k).TransitionID = CharOr(spec,'ID','');
        transitions(k).ParentCode = CharOr(spec,'ParentCode','');
        transitions(k).DaughterCode = CharOr(spec,'DaughterCode','');
        transitions(k).Status = CharOr(validation,'status','');
        transitions(k).Accepted = LogicalOr(validation,'accepted',false);
        transitions(k).ParentAccepted = LogicalOr(analysis,'accepted',false);
        transitions(k).CandidateType = CharOr(candidate,'Type','');
        transitions(k).BifurcationType = ...
            CharOr(candidate,'BifurcationType','');
        transitions(k).DetectedCoordinate = NumberOr(candidate, ...
            'ContinuationParameter',NaN);
        transitions(k).RefinedCoordinate = NumberOr(refinement, ...
            'coordinate',NaN);
        transitions(k).MultiplierResidual = NumberOr(refinement, ...
            'multiplierResidual',NaN);
        if isnumeric(multiplier) && isscalar(multiplier)
            transitions(k).CriticalMultiplier = multiplier;
        end
        transitions(k).ParameterErrorNormInf = NumberOr(validation, ...
            'parameterErrorNormInf',NaN);
        transitions(k).ScaledOrbitDistance22 = NumberOr(validation, ...
            'scaledOrbitDistance22',NaN);
        transitions(k).LinearDirectionAlignment = NumberOr(validation, ...
            'linearDirectionAlignment',NaN);
        transitions(k).MinimumCorrectionDirectionAlignment = ...
            NumberOr(validation,'minimumCorrectionDirectionAlignment',NaN);
        transitions(k).MaximumCorrectionDirectionAlignment = ...
            NumberOr(validation,'maximumCorrectionDirectionAlignment',NaN);
        transitions(k).CriticalPairStateError = NumberOr(validation, ...
            'criticalPairStateError',NaN);
        transitions(k).CriticalPairTimingError = NumberOr(validation, ...
            'criticalPairTimingError',NaN);
        transitions(k).DaughterPairStateError = NumberOr(validation, ...
            'daughterPairStateError',NaN);
        transitions(k).DaughterPairTimingError = NumberOr(validation, ...
            'daughterPairTimingError',NaN);
        transitions(k).DaughterGait = CharOr(validation,'daughterGait','');
        transitions(k).DaughterGaitAbbreviation = ...
            CharOr(validation,'daughterGaitAbbreviation','');
        transitions(k).NearPeriodicOrbitAccepted = LogicalOr( ...
            FieldOr(validation,'nearPeriodicValidation',struct()), ...
            'accepted',false);
        transitions(k).OutgoingPeriodicOrbitAccepted = LogicalOr( ...
            FieldOr(validation,'outgoingPeriodicValidation',struct()), ...
            'accepted',false);
        transitions(k).Assertions = ...
            FieldOr(validation,'assertions',struct());
        transitions(k).RejectionReasons = ...
            FieldOr(validation,'rejectionReasons',{});
        transitions(k).HeldOutDaughterFile = RelativePath( ...
            CharOr(validation,'daughterFile',''),paths.ExperimentRoot);
    end

    upstream = [ ...
        ArtifactIdentity('discovery',files.Discovery,paths.ExperimentRoot), ...
        ArtifactIdentity('refinement',files.Refinement,paths.ExperimentRoot), ...
        ArtifactIdentity('seed-search',files.Seeds,paths.ExperimentRoot), ...
        ArtifactIdentity('daughter-rays',files.Daughters,paths.ExperimentRoot)];
    authority = ArtifactIdentity('authoritative-result', ...
        authoritativeFile,paths.ExperimentRoot);
    authority.Variable = 'report';
    authority.ReportVersion = CharOr(report,'version','');
    payload = struct( ...
        'ArtifactRole','compact-index-to-authoritative-specialized-report', ...
        'ExperimentType','targeted-retrospective-reference', ...
        'Scope','validation-only-index', ...
        'Status',CharOr(report,'status',''), ...
        'Accepted',LogicalOr(report.summary,'accepted',false), ...
        'Summary',report.summary, ...
        'Transitions',transitions, ...
        'AuthoritativeResult',authority, ...
        'UpstreamStageArtifacts',upstream, ...
        'ClaimBoundary',[ ...
            'This compact Stage-5 record indexes validation evidence and ' ...
            'its authoritative report. It deliberately excludes Floquet ' ...
            'scans, refined eigensystems, seed attempts, and corrected ' ...
            'daughter payloads stored in Stages 1--4.']);
end

function value = EmptyValidationSummary()
    value = struct( ...
        'TransitionID','','ParentCode','','DaughterCode','', ...
        'Status','','Accepted',false,'ParentAccepted',false, ...
        'CandidateType','','BifurcationType','', ...
        'DetectedCoordinate',NaN,'RefinedCoordinate',NaN, ...
        'CriticalMultiplier',NaN,'MultiplierResidual',NaN, ...
        'ParameterErrorNormInf',NaN,'ScaledOrbitDistance22',NaN, ...
        'LinearDirectionAlignment',NaN, ...
        'MinimumCorrectionDirectionAlignment',NaN, ...
        'MaximumCorrectionDirectionAlignment',NaN, ...
        'CriticalPairStateError',NaN,'CriticalPairTimingError',NaN, ...
        'DaughterPairStateError',NaN,'DaughterPairTimingError',NaN, ...
        'DaughterGait','','DaughterGaitAbbreviation','', ...
        'NearPeriodicOrbitAccepted',false, ...
        'OutgoingPeriodicOrbitAccepted',false, ...
        'Assertions',struct(),'RejectionReasons',{{}}, ...
        'HeldOutDaughterFile','');
end

function identity = ArtifactIdentity(stage, filename, experimentRoot)
    if ~isfile(filename)
        error('WriteRoadmapStageArtifacts:MissingArtifact', ...
            'Cannot index missing %s artifact: %s',stage,filename);
    end
    details = dir(filename);
    identity = struct( ...
        'Stage',stage, ...
        'RelativePath',RelativePath(filename,experimentRoot), ...
        'SHA256',floquet.workflow.internal.FloquetFileSHA256(filename), ...
        'Bytes',details.bytes);
end

function value = RelativePath(filename, root)
    value = char(string(filename));
    root = char(string(root));
    prefix = [root filesep];
    if startsWith(value,prefix)
        value = value(numel(prefix)+1:end);
    end
    value = strrep(value,filesep,'/');
end

function record = StageRecord(schema, layout, stamp, payload)
    record = struct('SchemaVersion',schema, ...
        'ArtifactLayoutVersion',layout,'CreatedAt',stamp, ...
        'Payload',payload);
end

function [candidateTable, refinementTable, seedTable, daughterTable, ...
        validationTable] = SummaryTables(report, daughterItems)
    count = numel(report.transitions);
    TransitionID = string({report.transitions.ID}).';
    Parent = string({report.transitions.ParentCode}).';
    Daughter = string({report.transitions.DaughterCode}).';
    CandidateType = strings(count,1);
    DetectedCoordinate = NaN(count,1);
    RefinedCoordinate = NaN(count,1);
    MultiplierResidual = NaN(count,1);
    ParentAccepted = false(count,1);
    HeldOutAccepted = false(count,1);
    AttemptCount = zeros(count,1);
    AcceptedAttemptCount = zeros(count,1);
    for k = 1:count
        analysis = report.analyses(k);
        candidate = FieldOr(analysis,'candidate',struct());
        refinement = FieldOr(analysis,'refinement',struct());
        CandidateType(k) = string(FieldOr(candidate,'Type',''));
        DetectedCoordinate(k) = NumberOr(candidate, ...
            'ContinuationParameter',NaN);
        RefinedCoordinate(k) = NumberOr(refinement,'coordinate',NaN);
        MultiplierResidual(k) = NumberOr(refinement, ...
            'multiplierResidual',NaN);
        ParentAccepted(k) = LogicalOr(analysis,'accepted',false);
        HeldOutAccepted(k) = LogicalOr(report.validations(k), ...
            'accepted',false);
        attempts = FieldOr(analysis,'attempts',struct([]));
        AttemptCount(k) = numel(attempts);
        AcceptedAttemptCount(k) = ...
            numel(daughterItems(k).AcceptedAttempts);
    end
    candidateTable = table(TransitionID,Parent,Daughter,CandidateType, ...
        DetectedCoordinate,ParentAccepted);
    refinementTable = table(TransitionID,RefinedCoordinate, ...
        MultiplierResidual,ParentAccepted);
    seedTable = table(TransitionID,AttemptCount,AcceptedAttemptCount);
    daughterTable = table(TransitionID,AcceptedAttemptCount);
    validationTable = table(TransitionID,HeldOutAccepted);
end

function value = FieldOr(source, name, fallback)
    value = fallback;
    if isstruct(source) && isscalar(source) && isfield(source,name)
        value = source.(name);
    end
end

function value = NumberOr(source, name, fallback)
    value = FieldOr(source,name,fallback);
    if ~(isnumeric(value) && isreal(value) && isscalar(value) && ...
            isfinite(value))
        value = fallback;
    end
end

function value = CharOr(source, name, fallback)
    value = FieldOr(source,name,fallback);
    if (isstring(value) && isscalar(value) && ~ismissing(value)) || ...
            (ischar(value) && isrow(value))
        value = char(string(value));
    else
        value = fallback;
    end
end

function value = LogicalOr(source, name, fallback)
    value = FieldOr(source,name,fallback);
    if ~(isscalar(value) && (islogical(value) || ...
            (isnumeric(value) && isreal(value) && isfinite(value) && ...
             any(value == [0 1]))))
        value = fallback;
    end
    value = logical(value);
end

function ValidateInputs(report, paths)
    if ~isstruct(report) || ~isscalar(report) || ...
            ~all(isfield(report,{'transitions','analyses','validations'}))
        error('WriteRoadmapStageArtifacts:Report', ...
            'report must contain transitions, analyses, and validations.');
    end
    required = {'ExperimentRoot','ReferenceConfigFile','DiscoveryRoot', ...
        'RefinementRoot', ...
        'SeedSearchRoot','DaughterBranchesRoot','ValidationRoot', ...
        'CheckpointsRoot','ViewsRoot','LogRoot'};
    if ~isstruct(paths) || ~isscalar(paths) || ...
            ~all(isfield(paths,required))
        error('WriteRoadmapStageArtifacts:Paths', ...
            'paths does not satisfy the v2 reference layout contract.');
    end
end

function EnsureDirectory(folder)
    if ~isfolder(folder)
        mkdir(folder);
    end
end

function value = Timestamp()
    value = char(datetime('now','TimeZone','local', ...
        'Format','yyyy-MM-dd''T''HH:mm:ssXXX'));
end
