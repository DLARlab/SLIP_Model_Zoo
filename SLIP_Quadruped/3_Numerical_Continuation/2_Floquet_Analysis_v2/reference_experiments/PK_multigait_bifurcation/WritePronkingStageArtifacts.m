function files = WritePronkingStageArtifacts(report, paths)
%WRITEPRONKINGSTAGEARTIFACTS Split the completed PK reference by stage.

    ValidateInputs(report,paths);
    directories = {paths.DiscoveryRoot,paths.RefinementRoot, ...
        paths.SeedSearchRoot,paths.DaughterBranchesRoot, ...
        paths.ValidationRoot,paths.CheckpointsRoot,paths.ViewsRoot, ...
        paths.LogRoot};
    for k = 1:numel(directories)
        EnsureDirectory(directories{k});
    end
    stamp = Timestamp();
    layout = 'numbered-artifacts-v1';

    referenceConfig = struct( ...
        'SchemaVersion','floquet-reference-experiment-config-v2', ...
        'ArtifactLayoutVersion',layout, ...
        'ExperimentType','symmetry-resolved-multiple-plus-one-reference', ...
        'ExperimentRoot',paths.ExperimentRoot, ...
        'ParentFile',paths.PronkingBranchFile, ...
        'HeldOutDaughterDirectory',paths.DaughterBranchRoot, ...
        'CreatedAt',stamp, ...
        'WorkflowCompatibility', ...
            'specialized-four-dimensional-kernel-not-generic-single-mode', ...
        'InformationBarrier',[ ...
            'Held-out daughter branches are loaded only after discovery, ' ...
            'critical-orbit refinement, and symmetry resolution.']);
    configFile = paths.ReferenceConfigFile;
    save(configFile,'referenceConfig','-v7');

    discoveryReport = StageRecord('floquet-reference-discovery-v2', ...
        layout,stamp,report.floquetExperiment);
    refinementPayload = struct('Critical',report.critical, ...
        'Symmetry',report.symmetry);
    refinementReport = StageRecord('floquet-reference-refinement-v2', ...
        layout,stamp,refinementPayload);
    seedReport = StageRecord('floquet-reference-seed-search-v2', ...
        layout,stamp,report.nonlinearSearch);
    daughterPayload = struct( ...
        'ContinuationPerformed',false, ...
        'LocalCorrectedRays',FieldOr(report.nonlinearSearch, ...
            'clusters',struct([])), ...
        'HeldOutDaughters',report.daughterValidation.daughters, ...
        'Meaning',[ ...
            'The reference certifies local corrected rays and held-out ' ...
            'branch alignment; it does not claim new continuation output.']);
    daughterReport = StageRecord('floquet-reference-daughters-v2', ...
        layout,stamp,daughterPayload);
    files = struct();
    files.Config = configFile;
    files.Discovery = fullfile(paths.DiscoveryRoot,'floquet_analysis.mat');
    files.Candidates = fullfile(paths.DiscoveryRoot, ...
        'candidate_inventory.csv');
    files.Refinement = fullfile(paths.RefinementRoot, ...
        'refined_candidates.mat');
    files.RefinementSummary = fullfile(paths.RefinementRoot, ...
        'refinement_summary.csv');
    files.Seeds = fullfile(paths.SeedSearchRoot, ...
        'daughter_seed_search.mat');
    files.SeedAttempts = fullfile(paths.SeedSearchRoot, ...
        'daughter_seed_attempts.csv');
    files.Daughters = fullfile(paths.DaughterBranchesRoot,'inventory.mat');
    files.DaughterInventory = fullfile(paths.DaughterBranchesRoot, ...
        'inventory.csv');
    files.Validation = fullfile(paths.ValidationRoot, ...
        'validation_report.mat');
    files.ValidationSummary = fullfile(paths.ValidationRoot, ...
        'validation_summary.csv');

    % These retrospective projections are comfortably below the v7 size
    % limit. Compressed v7 preserves the complete numerical payload while
    % avoiding v7.3/HDF5 metadata expansion for deeply nested structures.
    save(files.Discovery,'discoveryReport','-v7');
    save(files.Refinement,'refinementReport','-v7');
    save(files.Seeds,'seedReport','-v7');
    save(files.Daughters,'daughterReport','-v7');

    authoritativeFile = fullfile(paths.ValidationRoot, ...
        'pronking_multigait_validation_results.mat');
    validationPayload = CompactValidationIndex(report,paths,files, ...
        authoritativeFile);
    validationReport = StageRecord( ...
        'floquet-reference-validation-index-v3',layout,stamp, ...
        validationPayload);
    save(files.Validation,'validationReport','-v7');
    writetable(CandidateTable(report),files.Candidates);
    writetable(RefinementTable(report),files.RefinementSummary);
    writetable(SeedTable(report),files.SeedAttempts);
    writetable(DaughterTable(report),files.DaughterInventory);
    writetable(ValidationTable(report),files.ValidationSummary);
end

function payload = CompactValidationIndex(report,paths,files, ...
        authoritativeFile)
%COMPACTVALIDATIONINDEX Retain conclusions without copying all prior stages.
    if ~isfile(authoritativeFile)
        error('WritePronkingStageArtifacts:AuthoritativeResult', ...
            ['Save the authoritative pronking result before materializing ' ...
             'the compact Stage-5 index: %s'],authoritativeFile);
    end

    refinement = report.critical.refinement;
    diagnostics = report.symmetry.diagnostics;
    search = report.nonlinearSearch;
    daughterValidation = report.daughterValidation;
    critical = struct( ...
        'Coordinate',NumberOr(refinement,'coordinate',NaN), ...
        'Multiplier',NumericOr(refinement,'multiplier',NaN), ...
        'MultiplierResidual',NumberOr(refinement, ...
            'multiplierResidual',NaN), ...
        'BracketWidth',NumberOr(refinement,'bracketWidth',NaN), ...
        'CanonicalResidualNormInf',NumberOr(refinement, ...
            'canonicalResidualNormInf',NaN), ...
        'CriticalMultiplierUncertainty',NumberOr(refinement, ...
            'criticalMultiplierUncertainty',NaN), ...
        'Accepted',LogicalOr(refinement,'accepted',false));
    symmetry = struct( ...
        'Accepted',LogicalOr(diagnostics,'accepted',false), ...
        'NumericalNullity',NumberOr(diagnostics,'numericalNullity',NaN), ...
        'AdditionalDimension',NumberOr(diagnostics, ...
            'additionalDimension',NaN), ...
        'MaximumScaledTangentOverlap',NumberOr(diagnostics, ...
            'maximumScaledTangentOverlap',NaN), ...
        'FullSectorRanks',NumericOr(diagnostics,'fullSectorRanks',[]), ...
        'AdditionalSectorRanks',NumericOr(diagnostics, ...
            'additionalSectorRanks',[]), ...
        'RelativeCommutatorNorms',NumericOr(diagnostics, ...
            'relativeCommutatorNorms',[]), ...
        'RejectionReasons',{FieldOr(diagnostics,'rejectionReasons',{})});
    nonlinearSearch = struct( ...
        'Status',CharOr(search,'status',''), ...
        'AttemptCount',NumberOr(search,'attemptCount',0), ...
        'PredictorAcceptedCount',NumberOr(search, ...
            'predictorAcceptedCount',0), ...
        'CorrectorAcceptedCount',NumberOr(search, ...
            'correctorAcceptedCount',0), ...
        'NonParentAcceptedCount',NumberOr(search, ...
            'nonParentAcceptedCount',0), ...
        'PersistentRayCount',NumberOr(search, ...
            'persistentClusterCount',0), ...
        'PersistentClassCounts',NumericOr(search, ...
            'persistentClassCounts',[]), ...
        'SixArmSearchValidated',LogicalOr(search, ...
            'sixArmSearchValidated',false), ...
        'BlindSixArmDiscoveryValidated',LogicalOr(search, ...
            'blindSixArmDiscoveryValidated',false));
    heldOut = struct( ...
        'Status',CharOr(daughterValidation,'status',''), ...
        'Accepted',LogicalOr(daughterValidation,'accepted',false), ...
        'DaughterDirectionRank',NumberOr(daughterValidation, ...
            'daughterDirectionRank',NaN), ...
        'PrincipalCosines',NumericOr(daughterValidation, ...
            'principalCosines',[]), ...
        'PrincipalAnglesDegrees',NumericOr(daughterValidation, ...
            'principalAnglesDegrees',[]), ...
        'Assertions',FieldOr(daughterValidation,'assertions',struct()), ...
        'Daughters',CompactDaughters(daughterValidation.daughters,paths));

    upstream = [ ...
        ArtifactIdentity('discovery',files.Discovery,paths.ExperimentRoot), ...
        ArtifactIdentity('refinement',files.Refinement,paths.ExperimentRoot), ...
        ArtifactIdentity('seed-search',files.Seeds,paths.ExperimentRoot), ...
        ArtifactIdentity('daughter-rays',files.Daughters,paths.ExperimentRoot)];
    authority = ArtifactIdentity('authoritative-result', ...
        authoritativeFile,paths.ExperimentRoot);
    authority.Variable = 'report';
    authority.ReportVersion = CharOr(report,'version','');
    payload = struct( ...
        'ArtifactRole','compact-index-to-authoritative-specialized-report', ...
        'ExperimentType','symmetry-resolved-multiple-plus-one-reference', ...
        'Scope','validation-only-index', ...
        'Status',CharOr(report,'status',''), ...
        'Accepted',strcmp(CharOr(report,'status',''),'verified'), ...
        'Conclusion',report.conclusion, ...
        'Critical',critical, ...
        'Symmetry',symmetry, ...
        'NonlinearSearch',nonlinearSearch, ...
        'HeldOutValidation',heldOut, ...
        'AuthoritativeResult',authority, ...
        'UpstreamStageArtifacts',upstream, ...
        'ClaimBoundary',[ ...
            'This compact Stage-5 record indexes the verified four-' ...
            'dimensional +1 kernel, six local rays, and held-out daughter ' ...
            'checks. It deliberately excludes the Floquet scan, complete ' ...
            'eigensystems, nonlinear attempt payloads, and saved orbits ' ...
            'stored in Stages 1--4 and the authoritative result. Held-out ' ...
            'global branches validate alignment; this package does not ' ...
            'claim that those curves were freshly continued in this run.']);
end

function summaries = CompactDaughters(daughters,paths)
    template = struct('Code','','SourceFile','','ExpectedClass','', ...
        'PredictedClass','','NearIndex',NaN,'OutgoingIndex',NaN, ...
        'NearCoordinate',NaN,'OutgoingCoordinate',NaN, ...
        'ParameterErrorNormInf',NaN,'ScaledOrbitDistance22',NaN, ...
        'TransverseAlignment',NaN,'AngleDegrees',NaN, ...
        'ProjectionResidual',NaN,'HindPairPhaseError',NaN, ...
        'FrontPairPhaseError',NaN,'Gait','', ...
        'GaitAbbreviation','','ClassificationMatches',false, ...
        'TimingSymmetryMatches',false,'PeriodicOrbitAccepted',false);
    summaries = repmat(template,1,numel(daughters));
    for k = 1:numel(daughters)
        item = daughters(k);
        summaries(k).Code = CharOr(item,'code','');
        summaries(k).SourceFile = RelativePath( ...
            CharOr(item,'file',''),paths.ExperimentRoot);
        summaries(k).ExpectedClass = CharOr(item,'expectedClass','');
        summaries(k).PredictedClass = CharOr(item,'predictedClass','');
        summaries(k).NearIndex = NumberOr(item,'nearIndex',NaN);
        summaries(k).OutgoingIndex = NumberOr(item,'outgoingIndex',NaN);
        summaries(k).NearCoordinate = NumberOr(item,'nearDx',NaN);
        summaries(k).OutgoingCoordinate = NumberOr(item,'outgoingDx',NaN);
        summaries(k).ParameterErrorNormInf = NumberOr(item, ...
            'parameterErrorNormInf',NaN);
        summaries(k).ScaledOrbitDistance22 = NumberOr(item, ...
            'scaledOrbitDistance22',NaN);
        summaries(k).TransverseAlignment = NumberOr(item, ...
            'transverseAlignment',NaN);
        summaries(k).AngleDegrees = NumberOr(item,'angleDegrees',NaN);
        summaries(k).ProjectionResidual = NumberOr(item, ...
            'projectionResidual',NaN);
        summaries(k).HindPairPhaseError = NumberOr(item, ...
            'hindPairPhaseError',NaN);
        summaries(k).FrontPairPhaseError = NumberOr(item, ...
            'frontPairPhaseError',NaN);
        summaries(k).Gait = CharOr(item,'gait','');
        summaries(k).GaitAbbreviation = CharOr(item,'abbreviation','');
        summaries(k).ClassificationMatches = LogicalOr(item, ...
            'classificationMatches',false);
        summaries(k).TimingSymmetryMatches = LogicalOr(item, ...
            'timingSymmetryMatches',false);
        summaries(k).PeriodicOrbitAccepted = LogicalOr(item, ...
            'periodicOrbitAccepted',false);
    end
end

function identity = ArtifactIdentity(stage,filename,experimentRoot)
    if ~isfile(filename)
        error('WritePronkingStageArtifacts:MissingArtifact', ...
            'Cannot index missing %s artifact: %s',stage,filename);
    end
    details = dir(filename);
    identity = struct( ...
        'Stage',stage, ...
        'RelativePath',RelativePath(filename,experimentRoot), ...
        'SHA256',floquet.workflow.internal.FloquetFileSHA256(filename), ...
        'Bytes',details.bytes);
end

function value = RelativePath(filename,root)
    value = char(string(filename));
    root = char(string(root));
    prefix = [root filesep];
    if startsWith(value,prefix)
        value = value(numel(prefix)+1:end);
    end
    value = strrep(value,filesep,'/');
end

function record = StageRecord(schema,layout,stamp,payload)
    record = struct('SchemaVersion',schema, ...
        'ArtifactLayoutVersion',layout,'CreatedAt',stamp, ...
        'Payload',payload);
end

function value = CandidateTable(report)
    candidates = report.floquetExperiment.candidates;
    count = numel(candidates);
    CandidateID = strings(count,1);
    Type = strings(count,1);
    ContinuationParameter = NaN(count,1);
    MultiplierReal = NaN(count,1);
    MultiplierImag = NaN(count,1);
    Confidence = NaN(count,1);
    for k = 1:count
        CandidateID(k) = "PK-C" + string(k);
        Type(k) = string(FieldOr(candidates(k),'Type',''));
        ContinuationParameter(k) = NumberOr(candidates(k), ...
            'ContinuationParameter',NaN);
        multiplier = FieldOr(candidates(k),'Multiplier',NaN);
        if isnumeric(multiplier) && isscalar(multiplier)
            MultiplierReal(k) = real(multiplier);
            MultiplierImag(k) = imag(multiplier);
        end
        Confidence(k) = NumberOr(candidates(k),'ConfidenceScore',NaN);
    end
    value = table(CandidateID,Type,ContinuationParameter, ...
        MultiplierReal,MultiplierImag,Confidence);
end

function value = RefinementTable(report)
    refinement = report.critical.refinement;
    Coordinate = NumberOr(refinement,'coordinate',NaN);
    MultiplierResidual = NumberOr(refinement,'multiplierResidual',NaN);
    BracketWidth = NumberOr(refinement,'bracketWidth',NaN);
    Accepted = LogicalOr(refinement,'accepted',false);
    Nullity = NumberOr(report.symmetry.diagnostics,'numericalNullity',NaN);
    AdditionalDimension = NumberOr(report.symmetry.diagnostics, ...
        'additionalDimension',NaN);
    value = table(Coordinate,MultiplierResidual,BracketWidth,Accepted, ...
        Nullity,AdditionalDimension);
end

function value = SeedTable(report)
    search = report.nonlinearSearch;
    AttemptCount = NumberOr(search,'attemptCount',0);
    AcceptedCount = NumberOr(search,'nonParentAcceptedCount',0);
    PersistentRayCount = NumberOr(search,'persistentClusterCount',0);
    BlindSixRayAccepted = LogicalOr(search, ...
        'blindSixArmDiscoveryValidated',false);
    value = table(AttemptCount,AcceptedCount,PersistentRayCount, ...
        BlindSixRayAccepted);
end

function value = DaughterTable(report)
    daughters = report.daughterValidation.daughters;
    count = numel(daughters);
    Code = strings(count,1);
    PredictedClass = strings(count,1);
    Alignment = NaN(count,1);
    PeriodicOrbitAccepted = false(count,1);
    for k = 1:count
        Code(k) = string(FieldOr(daughters(k),'code',''));
        PredictedClass(k) = string(FieldOr(daughters(k), ...
            'predictedClass',''));
        Alignment(k) = NumberOr(daughters(k),'transverseAlignment',NaN);
        PeriodicOrbitAccepted(k) = LogicalOr(daughters(k), ...
            'periodicOrbitAccepted',false);
    end
    value = table(Code,PredictedClass,Alignment,PeriodicOrbitAccepted);
end

function value = ValidationTable(report)
    Status = string(report.status);
    CriticalCoordinate = NumberOr(report.critical.refinement, ...
        'coordinate',NaN);
    Nullity = NumberOr(report.symmetry.diagnostics,'numericalNullity',NaN);
    AdditionalDimension = NumberOr(report.symmetry.diagnostics, ...
        'additionalDimension',NaN);
    PersistentRayCount = NumberOr(report.nonlinearSearch, ...
        'persistentClusterCount',0);
    value = table(Status,CriticalCoordinate,Nullity, ...
        AdditionalDimension,PersistentRayCount);
end

function value = FieldOr(source,name,fallback)
    value = fallback;
    if isstruct(source) && isscalar(source) && isfield(source,name)
        value = source.(name);
    end
end

function value = NumberOr(source,name,fallback)
    value = FieldOr(source,name,fallback);
    if ~(isnumeric(value) && isreal(value) && isscalar(value) && ...
            isfinite(value))
        value = fallback;
    end
end

function value = NumericOr(source,name,fallback)
    value = FieldOr(source,name,fallback);
    if ~isnumeric(value) || any(~isfinite(value(:)))
        value = fallback;
    end
end

function value = CharOr(source,name,fallback)
    value = FieldOr(source,name,fallback);
    if (isstring(value) && isscalar(value) && ~ismissing(value)) || ...
            (ischar(value) && isrow(value))
        value = char(string(value));
    else
        value = fallback;
    end
end

function value = LogicalOr(source,name,fallback)
    value = FieldOr(source,name,fallback);
    if ~(isscalar(value) && (islogical(value) || ...
            (isnumeric(value) && isreal(value) && isfinite(value) && ...
             any(value == [0 1]))))
        value = fallback;
    end
    value = logical(value);
end

function ValidateInputs(report,paths)
    requiredReport = {'floquetExperiment','critical','symmetry', ...
        'nonlinearSearch','daughterValidation','status'};
    if ~isstruct(report) || ~isscalar(report) || ...
            ~all(isfield(report,requiredReport))
        error('WritePronkingStageArtifacts:Report', ...
            'report is not a completed pronking reference report.');
    end
    requiredPaths = {'ExperimentRoot','ReferenceConfigFile', ...
        'PronkingBranchFile', ...
        'DaughterBranchRoot','DiscoveryRoot','RefinementRoot', ...
        'SeedSearchRoot','DaughterBranchesRoot','ValidationRoot', ...
        'CheckpointsRoot','ViewsRoot','LogRoot'};
    if ~isstruct(paths) || ~isscalar(paths) || ...
            ~all(isfield(paths,requiredPaths))
        error('WritePronkingStageArtifacts:Paths', ...
            'paths does not satisfy the v2 reference layout contract.');
    end
end

function EnsureDirectory(folder)
    if ~isfolder(folder)
        mkdir(folder);
    end
end

function value = Timestamp()
    value = char(datetime('now','TimeZone','local', ...
        'Format','yyyy-MM-dd''T''HH:mm:ssXXX'));
end
